import { describe, it, expect } from "vitest";
import { claimsReceiptSent, receiptNotSeenReply } from "../../src/ai/receiptClaim.js";
import { detectReplyLanguage } from "../../src/ai/clientLanguage.js";

/**
 * «Я отправила чек» без картинки (живой прогон 05.09.2026): такое сообщение
 * до модели доходить не должно — она верит слову «чек» и подтверждает то, чего
 * не получала.
 */
describe("claimsReceiptSent — человек говорит, что чек/оплата уже отправлены", () => {
  it.each([
    "Я оплатила, отправила чек, когда придёт ссылка?",
    "отправила чек",
    "Чек скинула",
    "вот чек",
    "Прикрепила скрин перевода",
    "Я оплатила",
    "заплатил вчера вечером",
    "Перевела деньги на карту",
    "Перевёл 70 сомони",
    "Ман пардохт кардам",
    "Чекро фиристодам",
    "чекаша партофтам апачон",
    "Пул равон кардам, ссылка кай меояд?",
    "пулро гузарондам",
    "ана чек",
  ])("ловит: %s", (text) => {
    expect(claimsReceiptSent(text)).toBe(true);
  });

  it.each([
    "Как отправить чек?",
    "Куда отправить чек?",
    "Не могу отправить чек",
    "Я ещё не оплатила",
    "Пока не заплатила, завтра переведу",
    "Сколько стоит курс?",
    "Здравствуйте",
    "Чек нужен обязательно?",
    "Ман ҳоло пардохт накардам",
    "Чекро нафиристодам",
    "Савол фиристодам, ҷавоб нест",
    "ок",
  ])("не ловит: %s", (text) => {
    expect(claimsReceiptSent(text)).toBe(false);
  });

  it("ответ на языке клиента; на сайте — про скрепку, в Instagram — «пришлите сюда»", () => {
    expect(receiptNotSeenReply("ru", true)).toContain("скрепкой");
    expect(receiptNotSeenReply("ru", false)).toContain("прямо сюда");
    expect(receiptNotSeenReply("tg", true)).toContain("Чекро ҳоло намебинам");
    expect(receiptNotSeenReply("tg", false)).toContain("ҳамин ҷо");
    expect(receiptNotSeenReply("en", true)).toContain("paperclip");
  });
});

/**
 * Детектор языка ОТВЕТА строже клиентского: «апачон» и «сомони» в русской
 * фразе бота — норма, а не повод перегенерировать.
 */
describe("detectReplyLanguage — на каком языке ответила модель", () => {
  it.each([
    "Кабул кардем апачон, хозир дохил мекнем",
    "Ҳо, мешавад",
    "Нархаш 70 сомони, апачон, чекро фиристед",
    "Ман ҳозир мебинам",
  ])("таджикский: %s", (text) => {
    expect(detectReplyLanguage(text)).toBe("tg");
  });

  it.each([
    "Курс стоит 70 сомони, апачон",
    "Чек пока не вижу — прикрепите фото чека скрепкой, и я сразу проверю.",
    "Ссылка на уроки придёт сюда же, обычно в течение часа",
    "Хуб, апачон — сейчас Ширин сама вам ответит",
  ])("русский: %s", (text) => {
    expect(detectReplyLanguage(text)).toBe("ru");
  });

  it("латиница без таджикских слов — английский", () => {
    expect(detectReplyLanguage("The course costs 70 somoni")).toBe("en");
  });
});
