import { describe, it, expect } from "vitest";
import { guardOffTopic } from "../../src/ai/offTopicGuard.js";

/**
 * КЛАСС ОШИБКИ: фильтр «попрошаек» глушил наши же предложения.
 * У курса есть бесплатный урок (ai/freeLessonHook.ts) и вопросы про рассрочку,
 * а FREELOADER молчал на любое «бесплатн…» / «ройгон»: клиентка с рекламы
 * бесплатного урока получала тишину, и сторож неотвеченных считал это нарочным
 * молчанием. Перенесено из закрытого PR 57 (15.11.2026).
 */
const isSilent = (text: string) => guardOffTopic(text)?.kind === "freeloader";

describe("бесплатный урок и рассрочка — бот отвечает", () => {
  it.each([
    "Здравствуйте, хочу бесплатный урок",
    "Где посмотреть бесплатный урок?",
    "можно пробный урок",
    "Скиньте бесплатный урок пожалуйста",
    "а урок бесплатный есть?",
    "Ссылку на бесплатного урока дайте",
    "дарси ройгон",
    "Дарси ройгон куҷо?",
    "бепул дарс доред?",
    "бесплатный дарс",
    "Есть рассрочка?",
    "можно оплатить по частям?",
  ])("«%s» — не молчим", (text) => {
    expect(isSilent(text)).toBe(false);
  });
});

describe("просьбы отдать курс даром — по-прежнему молчание", () => {
  it.each([
    "скиньте уроки бесплатно",
    "бесплатные уроки дайте",
    "дайте курс бесплатно",
    "пустите так, денег нет",
    "ройгон диҳед",
    "бепул",
  ])("«%s» — молчим", (text) => {
    expect(isSilent(text)).toBe(true);
  });
});

describe("оплатившая — отвечаем как раньше", () => {
  it("«оплатила, бесплатно не прошу» не глушится", () => {
    expect(isSilent("я оплатила, бесплатно не прошу, дайте доступ")).toBe(false);
  });
});
