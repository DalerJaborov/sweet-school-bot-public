-- Метка устройства, выдаваемая СЕРВЕРОМ (Device.secret).
--
-- Раньше устройство опознавалось по отпечатку, который собирал и присылал сам
-- браузер. Это обходилось одной строкой: покупательница смотрела своё значение
-- и диктовала подругам, и десять человек считались одним устройством — лимит
-- не тратился, тревоги не было. Теперь опознание идёт по случайной метке в
-- httpOnly-куке, а отпечаток остаётся лишь сведением для владельца.
--
-- Колонка nullable: миграция строго аддитивная, таблица не пересоздаётся.
-- Существующие записи (на момент миграции их нет) просто не опознаются по
-- куке и получат метку при следующем входе.
ALTER TABLE "Device" ADD COLUMN "secret" TEXT;

-- Уникальность: метка одного устройства не должна совпасть с чужой.
-- В SQLite несколько NULL уникальному индексу не мешают.
CREATE UNIQUE INDEX "Device_secret_key" ON "Device"("secret");
