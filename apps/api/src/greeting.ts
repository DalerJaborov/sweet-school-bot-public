import { prisma } from "./db.js";

/**
 * ОДНО ПРИВЕТСТВИЕ НА ПЕРЕПИСКУ — правило уровня всей отправки, а не отдельного
 * текста.
 *
 * ЗАЧЕМ ГЛОБАЛЬНО. Приветствие живёт в двух независимых местах: первый шаг
 * воронки («Ассалому алейкум, ба шумо кадом маълумот равон кунем?») и ветка,
 * которая начинается после нажатия кнопки («Ассалому алейкум 🌸, курси
 * кондитерии онлайн…»). Плюс третье — ответ ИИ, который здоровается по промту.
 * Каждое из них само по себе правильно, а вместе получается «здравствуйте» два
 * раза подряд за десять секунд. Вычистить это в текстах нельзя: как только
 * владелец отредактирует шаг в панели, приветствие вернётся.
 *
 * Поэтому срез стоит на ЕДИНСТВЕННОМ выходе наружу — в sendText/sendPrivateReply
 * из instagram.ts. Что бы ни отправлял код — воронка, ИИ, догоняющее — если с
 * этим человеком уже здоровались, приветствие из начала снимается.
 */

/** Приветствие в НАЧАЛЕ сообщения: таджикское, русское, со смайликами и без.
 *  Только начало строки — «салом» в середине фразы это уже не приветствие.
 *
 *  Обращение («апачон») входит в срез вместе с приветствием: без него остаток
 *  начинается с «апачон. Мо ду курси…» — обрубок, а не фраза. Смайлик после
 *  приветствия снимается целиком, включая модификатор тона кожи (👋🏻 — это ДВА
 *  символа, и без Emoji_Modifier в классе от него оставался висящий «🏻»). */
const LEADING_GREETING =
  /^\s*(ассалом[уy]?(\s*алейкум|\s*алайкум|\s*ъалайкум)?|салом(\s*алейкум)?|салам|здравствуйте|здрасте|привет|добрый\s+(день|вечер|утро))(?!\p{L})[\s!,.—-]*(апа[чҷ]он|ападжон|хо[ҳh]арам)?(?!\p{L})[\s!,.—-]*[\p{Extended_Pictographic}\p{Emoji_Modifier}‍️\s]*/iu;

/** Здоровались ли мы уже с этим человеком. Смотрим по всей переписке: если
 *  разговор возобновился через неделю, второе «здравствуйте» уместно — но это
 *  решает срок ниже, а не сам факт. */
const GREETING_AGAIN_AFTER_MS = 12 * 3_600_000; // полсуток тишины — можно снова

export async function alreadyGreeted(contactId: string): Promise<boolean> {
  const lastOut = await prisma.message.findFirst({
    where: { contactId, direction: "OUT", text: { not: null } },
    orderBy: { createdAt: "desc" },
    select: { createdAt: true },
  });
  if (!lastOut) return false;
  // Разговор давно остыл — новое приветствие звучит нормально, а не как второе
  // подряд. Это же спасает от «сухого» возврата к человеку через несколько дней.
  if (Date.now() - lastOut.createdAt.getTime() > GREETING_AGAIN_AFTER_MS) return false;

  // Ищем приветствие среди наших недавних сообщений, а не только в последнем:
  // между приветствием и веткой воронки лежит нажатие кнопки клиента.
  const recent = await prisma.message.findMany({
    where: { contactId, direction: "OUT", text: { not: null } },
    orderBy: { createdAt: "desc" },
    take: 10,
    select: { text: true },
  });
  return recent.some((m) => LEADING_GREETING.test(m.text as string));
}

/**
 * Снимает приветствие с начала текста, если с человеком уже здоровались.
 *
 * Если после среза не остаётся ничего (сообщение было ОДНИМ «Салом») — отдаём
 * текст как есть: лучше лишнее приветствие, чем пустое сообщение.
 */
export async function stripRepeatGreeting(contactId: string | null, text: string): Promise<string> {
  if (!contactId || !text || !LEADING_GREETING.test(text)) return text;
  if (!(await alreadyGreeted(contactId))) return text;
  const stripped = text.replace(LEADING_GREETING, "").replace(/^[\s\n]+/, "");
  if (stripped.length === 0) return text;
  // «Салом апачон. Мо ду курси…» после среза начинался бы со строчной буквы —
  // поднимаем первую, чтобы фраза читалась как самостоятельная.
  return stripped.charAt(0).toLocaleUpperCase("ru-RU") + stripped.slice(1);
}
