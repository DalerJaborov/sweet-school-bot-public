/**
 * Женский голос сообщений — как пишет сама Ширин.
 *
 * ПОЧЕМУ В КОДЕ, А НЕ В ПРОМТЕ. Промт — просьба, а не гарантия: модель нарушает
 * его тем чаще, чем длиннее разговор, и владелец уже ловил бота на этом. Две
 * вещи, по которым переписку сразу видно как «не её»:
 *
 *  1) ТОЧКА В КОНЦЕ. В мессенджере точка в конце фразы читается сухо и
 *     по-канцелярски — живые люди её просто не ставят. Убираем в конце каждой
 *     строки, но НЕ внутри абзаца: там точка разделяет предложения, без неё
 *     получится каша.
 *
 *  2) ЖЕСТЫ-РУКИ. 👋 🤝 👍 ☝️ — «мужские» деловые смайлики, в женском аккаунте
 *     кондитерской школы они звучат чужеродно. Ширин пишет цветами и сладким:
 *     🌸 💚 🎂 🍰. Руки заменяем, а не выкидываем — сообщение не должно остаться
 *     сухим там, где имелся в виду тёплый знак.
 */

/** Жесты и «деловые» знаки, которых в женском аккаунте быть не должно.
 *  Модификатор тона кожи (🏻) идёт отдельным символом — снимаем вместе. */
const MASCULINE_EMOJI =
  /(?:👋|🤝|👍|👌|✌️?|💪|👏|☝️?|🙏|🤙|✍️?|🫡|🤞|👊|✊)[\u{1F3FB}-\u{1F3FF}]?[️‍]?/gu;

/** Чем заменяем — по кругу, чтобы в длинном сообщении не повторялось одно и то же. */
const FEMININE_EMOJI = ["🌸", "💚", "🎂", "🍰"];

export function feminizeEmoji(text: string): string {
  let i = 0;
  return text.replace(MASCULINE_EMOJI, () => FEMININE_EMOJI[i++ % FEMININE_EMOJI.length]);
}

/**
 * Убирает точку в конце строки. Многоточие и «!?» не трогаем: это интонация, а
 * не сухость. Точка перед закрывающим смайликом тоже снимается — «спасибо. 💚»
 * читается так же официально, как «спасибо.».
 */
export function dropTrailingDots(text: string): string {
  return text
    .split("\n")
    .map((line) => {
      const trimmed = line.replace(/[ \t]+$/, "");
      // Хвост из смайликов/пробелов оставляем на месте, точку перед ним убираем.
      const m = /^(.*?)(\.)((?:[\s\p{Extended_Pictographic}\p{Emoji_Modifier}️‍])*)$/u.exec(trimmed);
      if (!m) return trimmed;
      const [, body, , tail] = m;
      if (body.endsWith(".")) return trimmed; // многоточие — не трогаем
      return body + tail;
    })
    .join("\n");
}

/** Полная правка исходящего текста. Вызывается на самом выходе наружу. */
export function toOwnerVoice(text: string): string {
  return dropTrailingDots(feminizeEmoji(text));
}
