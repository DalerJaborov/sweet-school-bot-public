/**
 * ПУСТЯКИ В ПЕРЕПИСКЕ: благодарность, «ок», «хоб», приветствие, смайлики.
 * Такое сообщение не требует ответа человека, и показывать его хозяйке в
 * «Сегодня» незачем — если захочет, прочитает сама в Instagram.
 *
 * Правило простое и намеренно строгое: сообщение пустяк, только если ВСЕ его
 * слова — из списка пустых слов (или слов нет вовсе, один смайлик). Стоит в
 * нём хоть одно другое слово («рахмат, а сколько стоит?») — это уже вопрос.
 */
const TRIVIAL_WORDS = new Set(
  [
    // благодарность
    "рахмат", "рахмат", "ташаккур", "ташакур", "ташаккури", "спасибо", "спс", "благодарю", "мерси", "большое", "вам", "огромное", "калон", "зур", "сизга", "шумо",
    // согласие и «понятно»
    "ок", "окей", "окэй", "ok", "okay", "ok", "хоб", "хуб", "хорошо", "ладно", "понятно", "ясно", "добро", "майли", "майла", "майлаш", "чашм", "да", "ха", "нет", "не",
    // приветствия и прощания
    "салом", "салам", "привет", "здравствуйте", "здравствуй", "ассалому", "ассалом", "алайкум", "алейкум", "воалейкум", "валейкум", "асалом", "асаллому", "ва", "мархамат", "пока", "хайр", "худо", "хофиз", "нигахдор",
    "добрый", "доброе", "день", "вечер", "утро", "ночи", "рӯз", "бахайр", "хуш", "омадед", "шумо",
  ].map((w) => w.toLowerCase()),
);

export function isTrivialMessage(text: string | null | undefined): boolean {
  const raw = (text ?? "").toLowerCase().replace(/ё/g, "е");
  // Только буквы и цифры; смайлики, знаки и пробелы — разделители.
  const words = raw.split(/[^\p{L}\p{N}]+/u).filter(Boolean);
  if (words.length === 0) return true; // пусто или одни смайлики/знаки
  return words.every((w) => TRIVIAL_WORDS.has(w) || /^\d{1,2}$/.test(w));
}

/** Вид события, который сам по себе ничего не просит: реакция, стикер. */
export function isTrivialKind(kind: string | null | undefined): boolean {
  return /reaction|sticker|react/i.test(kind ?? "");
}
