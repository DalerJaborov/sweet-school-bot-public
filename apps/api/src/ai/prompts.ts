/** Реквизиты одной строкой, как просил владелец: «905 355 355 Чаборова Фарангис (Душанбе Сити, Алиф)». */
export function paymentLine(t: Pick<SalesTexts, "paymentPhone" | "paymentRecipient" | "paymentBanks">): string {
  return `${t.paymentPhone} ${t.paymentRecipient} (${t.paymentBanks})`;
}

