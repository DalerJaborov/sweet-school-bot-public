import type { PriceTable } from "../prices.js";
import { COURSE_50, COURSE_70 } from "../prices.js";
import type { ClientLanguage } from "./clientLanguage.js";

/**
 * ГОТОВЫЕ ВОПРОСЫ INSTAGRAM («часто задаваемые» под кнопкой «Написать»).
 *
 * Instagram сам подсовывает новому человеку четыре вопроса, и тот нажимает их
 * первым сообщением. Разбор 11.11.2026: на них уходило меню воронки, а ИИ потом
 * выдумывал («сертификат сам появится в программе»). Тексты вопросов задал
 * владелец в Instagram и они неизменны, поэтому ответ на них — точный и из
 * фактов: цены из «Цены и даты», остальное — из фактов промпта владельца
 * (курс остаётся навсегда, рецепты отдельно не продаются, сертификат есть).
 *
 * Ответ — на языке клиента (вопрос по-русски, но если человек уже писал
 * по-таджикски, отвечаем по-таджикски), коротко и с одним лёгким шагом дальше.
 */
export type InstagramFaq = "duration" | "single_recipes" | "certificate" | "about";

/** Вопрос без знаков и регистра; «kursa» — так Instagram иногда пишет латиницей. */
function normalize(text: string): string {
  return text
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/kursa/g, "курса")
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}

const FAQ: { kind: InstagramFaq; re: RegExp }[] = [
  { kind: "duration", re: /^как долго доступен курс$/u },
  { kind: "single_recipes", re: /^можно ли купить отдельные рецепты$/u },
  { kind: "certificate", re: /^включает ли стоимость курса сертификат$/u },
  { kind: "about", re: /^расскажите подробнее о вашей компании$/u },
];

export function detectInstagramFaq(text: string | null | undefined): InstagramFaq | null {
  const n = normalize(text ?? "");
  if (!n) return null;
  return FAQ.find((f) => f.re.test(n))?.kind ?? null;
}

export function instagramFaqAnswer(kind: InstagramFaq, language: ClientLanguage, p: PriceTable): string {
  const c50 = p.price[COURSE_50];
  const c70 = p.price[COURSE_70];
  const tg = language === "tg";
  switch (kind) {
    case "duration":
      return tg
        ? `Курс хамеша дар шумо мемонад, як бор мехарен, дарсхо удалить намешан. Дарсхоя дар Telegram-группа ё дар сайти мо мебинен, кадомаш ба шумо осон бошад.\nКадом курс маъкул: 21 рецепт ${c70} сомони ё арт десерт ${c50} сомони?`
        : `Курс остаётся у вас навсегда: покупаете один раз, уроки не удаляются. Смотреть можно в Telegram-группе или на нашем сайте, как вам удобнее.\nКакой курс вам интересен: 21 рецепт за ${c70} сомони или арт-десерты за ${c50}?`;
    case "single_recipes":
      return tg
        ? `Рецептхо алохида фурухта намешан, факат курс пурра. 21 рецепт ${c70} сомони, арт десерт 9 намуд ${c50} сомони, харду курс якчоя ${p.bundle} сомони.\nКадомаш ба шумо маъкул?`
        : `Рецепты отдельно не продаются, только курс целиком. 21 рецепт за ${c70} сомони, арт-десерты (9 видов) за ${c50}, оба курса вместе за ${p.bundle}.\nКакой вам интересен?`;
    case "certificate":
      return tg
        ? `Ха, сертификат ба нарх дохил аст, пули иловаги намегирем.\nКадом курс маъкул: онлайн ё офлайн дар Душанбе?`
        : `Да, сертификат входит в стоимость, доплачивать за него не нужно.\nВам интересен онлайн-курс или офлайн в Душанбе?`;
    case "about":
      return tg
        ? `Ин курсхои муаллифии Ширин, кондитер аз Душанбе. Ду курси онлайн дорем ва як курси офлайн дар Душанбе.\nКадомаш ба шумо маъкул?`
        : `Это авторские курсы Ширин, кондитера из Душанбе. Есть два онлайн-курса и офлайн-курс в Душанбе.\nКакой вам интересен?`;
  }
}
