/**
 * ВРЕМЯ НА ЧЕКЕ — ДУШАНБИНСКОЕ, А КОНТЕЙНЕР ЖИВЁТ В UTC (22.08.2026).
 *
 * Модель возвращает дату строкой без часового пояса — «2026-08-21T14:30:00», ровно
 * так, как она напечатана на чеке. `new Date()` понимает такую строку как локальное
 * время процесса, а в контейнере это UTC. Разница в пять часов превращала свежий чек
 * в «дату из будущего», и оплата уходила владельцу на ручную проверку.
 *
 * Живой случай этого дня: перевод 70 сомони прошёл, реквизиты и сумма сошлись, а
 * вердикт — «suspicious, дата на чеке из будущего». Человек заплатил и остался без
 * доступа, пока сестра владельца не выдала ссылку руками.
 *
 * Смещение берётся из настройки `timezoneOffsetHours` (её же читают отчёты и ночное
 * обучение), дефолт 5 — Душанбе. Строка СО зоной («…+05:00», «…Z») не трогается:
 * в ней всё уже сказано.
 */
export const DEFAULT_OFFSET_HOURS = 5;
const HAS_TIMEZONE = /(?:Z|[+-]\d{2}:?\d{2})$/i;

export function parseReceiptDate(raw: string, offsetHours: number): Date | null {
  const value = raw.trim();
  if (!value) return null;
  const parsed = new Date(HAS_TIMEZONE.test(value) ? value : `${value}Z`);
  if (Number.isNaN(parsed.getTime())) return null;
  // Строку без зоны разобрали как UTC, а напечатана она по местному времени —
  // значит настоящий момент раньше на величину смещения.
  return HAS_TIMEZONE.test(value) ? parsed : new Date(parsed.getTime() - offsetHours * 3_600_000);
}
