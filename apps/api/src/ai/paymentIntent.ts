import { COURSE_50, COURSE_70, type Course } from "../prices.js";

/**
 * НАМЕРЕНИЯ КЛИЕНТА ВОКРУГ ОПЛАТЫ — ОДНО МЕСТО ДЛЯ ВСЕХ СЛОВ (16.11.2026).
 *
 * Разбор 16.11: после #86 номер карты доходил 1–3 людям в день вместо 7–17, а
 * конверсия Instagram в оплату упала с 10% до 2%. Бот спрашивал «отправить
 * реквизиты?» вместо номера, а «завтра переведу» оставалось без напоминания.
 *
 * Здесь только распознавание по словам, без базы и без решений:
 *  - priceOrChoice — спросил цену / «хочу купить» / выбрал курс → цена и номер
 *    сразу (ai/requisitesOffer.ts);
 *  - declinesPayment — «не надо», «позже», «баъдтар» → номер не навязываем
 *    (ai/repeatGuard.ts);
 *  - defersPayment — «завтра переведу», «пагоҳ», «посоветуюсь с мужем» → одно
 *    напоминание через ~20 часов (paymentReminder.ts).
 * Одна функция на смысл: все три места спрашивают здесь, а не держат свои списки.
 */

function norm(text: string | null | undefined): string {
  return (text ?? "").normalize("NFC").toLowerCase().replace(/ё/g, "е").trim();
}

/** Про офлайн-курс в Душанбе номер карты не даём: туда записывает Ширин. */
const OFFLINE = /офлайн|оффлайн|offline|дар\s+назди|назди\s+ман|очн\p{L}*|в\s+душанбе|курси\s+зинда|зинда\s+курс/iu;

/** Уже заплатил («перевела», «пардохт кардам») — это про чек, а не про номер. */
const ALREADY_PAID =
  /(оплатил\p{L}*|перевел\p{L}*|скинул\p{L}*|отправил\p{L}*\s+(деньги|чек|оплат)|пардохт\s+кард\p{L}*|партофт\p{L}*|гузаронд\p{L}*|фиристод\p{L}*|равон\s+кард\p{L}*|[хҳ]аридам|купил\p{L}*)/iu;

/** Вопрос о цене или прямое «хочу купить / как оплатить». */
const PRICE_ASK = new RegExp(
  [
    "сколько\\s+(стоит|стоят|будет|сомон|денег|за\\s+курс|по\\s+цене)",
    "^сколько\\s*\\?*$",
    "(?<!\\p{L})цен[аыуе](?!\\p{L})",
    "стоимост",
    "почем",
    "(?<!\\p{L})нар[хҳ]",
    "(?<!\\p{L})чанд\\s*(пул|сомон|сом(?!\\p{L})|пулаш|пулша|пулай|пули)",
    "(?<!\\p{L})чанд\\s*(аст|мешавад|мешад|мешан)(?!\\p{L})",
    "^чанд\\s*\\?*$",
    "\\d{2,3}\\s*(сомон\\p{L}*|сом(?!\\p{L}))[^.!\\n]*\\?",
    "(?<!\\p{L})[хҳ]арид(?!ор)",
    "мехарам|мехарем|харидан\\s+мехо",
    "хочу\\s+(купить|оплатить|приобрести|взять|записаться\\s+на\\s+онлайн)",
    "(?<!\\p{L})купить(?!\\p{L})",
    "как\\s+(оплатить|заплатить|купить|перевести)",
    "куда\\s+(перев|оплат|скин|отправ|плат)",
    "номер\\p{L}*\\s*(карт|для\\s+оплат)",
    "(?<!\\p{L})(ра[кқ]ам|номер)\\p{L}*\\s*(корт|карт)",
    "реквизит",
    "(чи\\s*[хҳ]ел|чихел|чӣ\\s*[хҳ]ел)\\s+(пардохт|пул\\s+партоям|гузаронам|харам)",
    "пул\\s+(партоям|гузаронам|равон\\s+кунам)",
  ].join("|"),
  "iu",
);

/** Короткое сообщение — это выбор курса («21 рецепт», «арт», «ҳарду»), а не рассказ. */
const BOTH = /(?<!\p{L})([хҳ]арду\p{L}*|оба(?!\p{L})|обоих|оба\s+курса|[хҳ]ар\s+ду|ду\s+курс\p{L}*|both|иккала)/iu;
const RE_70 = /(?<!\d)21(?!\d)|бисту\s+як|двадцать\s+од\p{L}*|(?<!\d)70(?!\d)/iu;
const RE_50 = /(?<!\p{L})арт(?!\p{L})|арт[\s-]*(десерт|ширин)\p{L}*|art[\s-]*dessert|(?<!\d)50(?!\d)/iu;
/** Вопрос про что-то другое («21 рецепт чиҳо дорад?», «какие десерты в арт?») — не выбор. */
const OTHER_QUESTION =
  /(какие|какой|что\s+(входит|там)|чи[ҳх]о|чи\s+дорад|кадом\p{L}*|чанд\s+(рӯз|руз|дарс|соат|вакт|вақт|рецепт)|сколько\s+(дней|уроков|длит|рецепт)|кай|когда|сертификат|телеграм|сайт)/iu;

export type PriceTopic = { courses: Course[]; bundle: boolean };

/** Какие курсы названы (оба — bundle). Пусто — курс не назван, цены всех. */
export function namedCourses(text: string): PriceTopic {
  const t = norm(text);
  const bundle = BOTH.test(t);
  const courses: Course[] = [];
  if (RE_70.test(t)) courses.push(COURSE_70);
  if (RE_50.test(t)) courses.push(COURSE_50);
  return { courses, bundle };
}

function isCourseChoice(t: string): boolean {
  const words = t.replace(/[\p{Extended_Pictographic}‍️]/gu, " ").split(/[^\p{L}\p{N}]+/u).filter(Boolean);
  if (words.length === 0 || words.length > 5) return false;
  if (OTHER_QUESTION.test(t)) return false;
  const { courses, bundle } = namedCourses(t);
  return bundle || courses.length > 0;
}

/**
 * Спросил цену, сказал «хочу купить» или выбрал курс — значит, сейчас уместны
 * цена и номер карты одним сообщением. null — номер к ответу не приклеиваем.
 */
export function priceOrChoice(text: string | null | undefined): PriceTopic | null {
  const t = norm(text);
  if (!t) return null;
  if (OFFLINE.test(t) || ALREADY_PAID.test(t)) return null;
  if (PRICE_ASK.test(t) || isCourseChoice(t)) return namedCourses(t);
  return null;
}

/** «Не надо», «позже», «пока нет», «баъдтар», «ҳоло не» — номер больше не навязываем. */
const DECLINE =
  /(не\s+надо|не\s+нужн\p{L}*|пока\s+нет|пока\s+не(?!\p{L})|не\s+хочу|не\s+интересно|не\s+буду|передумал\p{L}*|(?<!\p{L})позже(?!\p{L})|(?<!\p{L})потом(?!\p{L})|баъдтар|бадтар|лозим\s+нест|лозим\s+не|даркор\s+нест|даркор\s+не|на\s*мехо[хҳ]ам|[хҳ]оло\s+не(?!\p{L})|[хҳ]оло\s+(лозим|даркор)|[хҳ]оло\s+нест)/iu;
/** Отсрочка с намерением заплатить — это не отказ («позже переведу»). */
const PAY_LATER_VERB =
  /(переведу|оплачу|скину|отправлю|заплачу|куплю|мепартоям|мепартоем|мефиристам|мегузаронам|мегузаронем|пардохт\s+мекунам|пардохт\s+мекунем|мехарам|мехарем|пул\s+мемонам|мемонам)/iu;

export function declinesPayment(text: string | null | undefined): boolean {
  const t = norm(text);
  if (!t) return false;
  return DECLINE.test(t) && !PAY_LATER_VERB.test(t);
}

/** «Завтра переведу», «пагоҳ», «посоветуюсь», «картамда пул мемонам», «шавҳарам мепартояд». */
const DEFER = new RegExp(
  [
    "(?<!\\p{L})паго[хҳ]",
    "(?<!\\p{L})завтра(?!\\p{L})",
    "маслі?[ҳх]ат\\s+(кунам|мекунам|карда)",
    "маслихат|маслиҳат",
    "посоветую",
    "посоветоваться",
    "подумаю",
    "фикр\\s+(кунам|мекунам|карда)",
    "картам\\p{L}*\\s+пул\\s+(мемонам|монам|мепартоям)",
    "пул\\s+(мемонам|монам)",
    "(ша[вф][ҳх]арам|мардакам|мужем|муж\\s|шавхар)\\p{L}*[^.!?\\n]{0,30}(мепартояд|мефиристад|медиҳад|медихад|переведет|отправит|скинет|маслиҳат|маслихат)",
    "с\\s+мужем",
    "як[\\s-]*ду\\s+р[ӯу]з",
    "через\\s+(день|пару\\s+дней|два\\s+дня|\\d+\\s+дн)",
    "(?<!\\p{L})баъдан",
    "позже\\s+(переведу|оплачу|скину|отправлю)",
    "вечером\\s+(переведу|оплачу|скину)",
    "зарплат",
    "моя[нш]\\p{L}*\\s+(гирам|гирифта)",
  ].join("|"),
  "iu",
);
/** Отказ насовсем («не надо», «не хочу») — не отсрочка, напоминание не шлём. */
const HARD_NO = /(не\s+надо|не\s+нужн\p{L}*|не\s+хочу|не\s+интересно|передумал\p{L}*|лозим\s+нест|даркор\s+нест|на\s*мехо[хҳ]ам)/iu;

export function defersPayment(text: string | null | undefined): boolean {
  const t = norm(text);
  if (!t || HARD_NO.test(t) || ALREADY_PAID.test(t)) return false;
  return DEFER.test(t);
}
