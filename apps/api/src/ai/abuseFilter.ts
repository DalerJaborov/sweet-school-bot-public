/**
 * Мусор под роликами школы: флирт («красавица, познакомимся?»), оскорбления,
 * рекламный спам («накрутка подписчиков, пиши в директ»). Такое НЕ отвечаем и НЕ
 * пускаем в ИИ — удаляем комментарий, чтобы не висел под роликом.
 *
 * Отдельно от offTopicGuard нарочно: там «не по теме» (человеку отвечают вежливым
 * шаблоном и разговор продолжается), здесь — мусор, который вообще не должен
 * висеть публично. Разное действие, разные списки.
 *
 * Ловим только то, что нельзя спутать с живым вопросом про курс: ошибиться здесь
 * дороже, чем пропустить — удалённый комментарий настоящей клиентки не вернуть.
 */

const rx = (parts: string[]): RegExp => new RegExp(parts.join("|"), "iu");

/** Знакомства и флирт — самый частый мусор в директе и комментариях у женских
 *  аккаунтов. Обращения («красавица») сами по себе не ловим: так пишут и клиентки
 *  друг другу под рецептами — нужен признак ЗНАКОМСТВА рядом. */
const FLIRT = rx([
  "познаком(имся|иться|люсь)|давай\\s+познаком",
  // Просьба дать номер ШКОЛЫ — обычное дело у клиенток, поэтому ловим только
  // обращение на «ты» к самому человеку: «твой номер», «нет ли у тебя номера».
  "тво(й|его)\\s+номер|номер\\s+твой(?!\\p{L})|нет\\s+ли\\s+у\\s+теб[яе]\\s+номер",
  // «Замужем?» без обращения на «ты» — это может быть и рассказ о себе
  // («я замужем, есть вечерние группы?»), поэтому нужен вопрос ИМЕННО о ней.
  "т[ыи]\\s+замужем|шумо\\s+шав[ҳх]ар\\s+доред|ту\\s+шав[ҳх]ар\\s+дор",
  "дӯст\\s+мешавем|дуст\\s+мешавем|шинос\\s+шавем",
  "\\b(hey\\s+beautiful|hi\\s+beautiful|sexy|hot\\s+girl)\\b",
  "люблю\\s+теб|ман\\s+туро\\s+дуст|ман\\s+туро\\s+дӯст",
  "выходи\\s+замуж|замуж\\s+за\\s+мен",
  // Таджикский флирт из живых сообщений 05.09.2026: «зан мешавӣ?», «ба ман зан
  // шав», «ошиқ шудам», «шахсӣ гап занем». Просьбу дать номер WhatsApp сюда НЕ
  // кладём — так же пишут и настоящие покупательницы.
  "зан\\s+меш(ав[иӣ]|авед)|ба\\s+ман\\s+зан\\s+шав|ошиқ\\s+шуд|ошик\\s+шуд",
  "шахс[иӣ]\\s+гап\\s+зан(ем|[иӣ])|танҳо\\s+гап\\s+занем",
]);

/** Оскорбления и явная грубость. Список короткий и однозначный: спорные слова
 *  сюда не кладём вовсе — лучше пропустить, чем удалить живого человека. */
const INSULT = rx([
  // Хвост `(\p{L}*)?` раньше сводил границу слова на нет: «Дурахшон» (женское имя)
  // читалось как «дура», а «разводите желатин» — как «развод». Окончания теперь
  // перечислены явно, и каждая ветка закрыта с обеих сторон.
  "(?<!\\p{L})(дур[аы]|дурак|идиот(ка)?|тупа[яй]|тупой|уродк?а|шлюх[аиу]|сволоч[ьи]|мраз[ьи]|ничтожество)(?!\\p{L})",
  // «а то мошенники кругом» пишут осторожные клиентки, проверяя, настоящая ли
  // школа — за такое комментарий удалять нельзя. Только прямые обвинения нам.
  "(?<!\\p{L})(обманщи[кц]\\p{L}*|обманываете|обманули|воровк[аи])(?!\\p{L})",
  "\\b(fuck|bitch|stupid)\\b",
  "(?<!\\p{L})(аблах|бехаё|бешарм)(?!\\p{L})",
]);

/** Рекламный спам: чужие услуги, накрутка, ставки, займы. */
const SPAM = rx([
  "накрутк|подписчик(ов|и)\\s+(деш|недор|куп)|продвижен(ие|ию)\\s+аккаунт",
  "заработ(ок|ать)\\s+(в\\s+интернете|дома|онлайн)|доход\\s+от\\s+\\d",
  "ставк(и|а)\\s+на\\s+спорт|букмекер|казино|1xbet|melbet",
  // «займ» подстрокой ловил «займёмся десертами» — только целое слово.
  "(?<!\\p{L})займ[ыа]?(?!\\p{L})|кредит\\s+без|быстрые\\s+деньги|инвестиц",
  "пиши(те)?\\s+в\\s+(лс|директ)\\s+заработ",
  "\\b(crypto|forex|binary\\s+option|investment\\s+opportunity)\\b",
  "follow\\s+me|подпишись\\s+взаимно|взаимная\\s+подписка|л4л|f4f",
]);

export type AbuseKind = "flirt" | "insult" | "spam";

/** null — обычный комментарий, работаем как всегда. */
export function detectAbuse(text: string): AbuseKind | null {
  const trimmed = text.trim();
  if (trimmed.length < 3) return null;
  if (FLIRT.test(trimmed)) return "flirt";
  if (INSULT.test(trimmed)) return "insult";
  if (SPAM.test(trimmed)) return "spam";
  return null;
}
