/** Виды, на которые бот не отвечает НИЧЕМ — ни шаблоном, ни через модель. */
const SILENT_KINDS = new Set<GuardKind>(["freeloader"]);

/** Сужает тип: после проверки в коде остаётся только «говорящий» вид, и вызвать
 *  guardReply с несуществующим шаблоном становится невозможно. */
export function isSilentKind(kind: GuardKind): kind is Exclude<GuardKind, SpeakingKind> {
  return SILENT_KINDS.has(kind);
}

/**
 * ПРИГЛАШЕНИЕ В ТЕЛЕГРАМ-ГРУППУ — ТОЛЬКО УЧЕНИЦАМ (владелец 22.08.2026).
 *
 * Ответ на вопрос про рецепт зовёт написать в чат телеграм-группы. Но группа
 * ЗАКРЫТАЯ: туда входят только оплатившие курс. Звать туда любого, кто спросил про
 * крем, — значит либо отправить человека в дверь, которая для него не откроется,
 * либо раздать бесплатно то, за что берут деньги.
 *
 * Живой случай этого дня: женщина спросила про торт, ей ответили «по рецептам у нас
 * чат в телеграм-группе, напишите туда» — а она ничего не покупала.
 *
 * Тем, кто не купил, отвечаем просто и честно: подсказать не сможем. БЕЗ приглашения
 * и БЕЗ допродажи курса — правило «не навязывать» действует и здесь.
 */
const RECIPE_FOR_GUEST: Record<ClientLanguage, string> = {
  ru: "По рецептам подсказать не смогу",
  tg: "Оид ба рецепт гуфта наметонам",
  en: "Sorry, I can't help with recipes",
};

/**
 * @param isStudent человек оплатил курс — только ему можно звать в закрытый чат.
 */
export function guardReply(kind: SpeakingKind, language: ClientLanguage, isStudent = false): string {
  if (kind === "recipe_question" && !isStudent) return RECIPE_FOR_GUEST[language];
  return REPLIES[kind][language];
}

/** Наш ли это шаблонный ответ — считаем по самой переписке, без отдельного
 *  счётчика в базе. С `kind` — только шаблон этого вида. */
export function isGuardReply(text: string, kind?: SpeakingKind): boolean {
  const trimmed = text.trim();
  const groups = kind ? [REPLIES[kind]] : Object.values(REPLIES);
  // Гостевой вариант ответа про рецепты — тоже наш шаблон: без него счётчик
  // «сколько раз уже сказали» не увидит его и бот повторит одно и то же.
  if (kind === undefined || kind === "recipe_question") groups.push(RECIPE_FOR_GUEST);
  return groups.some((byLang) => Object.values(byLang).some((r) => r === trimmed));
}

/**
 * ПРЯМАЯ ПРОСЬБА ПОКАЗАТЬ МЕНЮ КУРСА — не КАК готовить (это RECIPE_HOWTO выше),
 * а ЧТО входит в курс. Раньше на такой вопрос модель раз за разом печатала
 * полотном все 20+ позиций меню из промта — теперь код ловит вопрос раньше
 * модели и (см. ai/menuImages.ts) шлёт готовую картинку-меню, ту же самую, что
 * уже уходит на шаге 11/21 воронки. Решение владельца 24.08.2026.
 *
 * ДО этой отсечки в guardOffTopic() уже отработали RECIPE_HOWTO (вопрос про
 * саму готовку — тот код тоже содержит слово «рецепт», но раньше в файле) и
 * WANTS_HUMAN/ORDER_REQUEST — так что сюда доходят только настоящие просьбы
 * показать список.
 */
const MENU_WORDS = rx([
  "чанд\\s+намуд|неча\\s+намуд|чи\\s+намуд|чӣ\\s+намуд",
  "какие\\s+(рецепт|десерт|сладост)|список\\s+рецепт|что\\s+входит",
  "меню\\s+курс|покажите\\s+меню|скинь(те)?\\s+меню|пришли(те)?\\s+меню",
]);

/** Слово «рецепт» есть, но в форме с таджикским суффиксом («рецептхоро» —
 *  рецепты-их) — точное «рецепт(и|а|ро)?\\s+равон» такое не ловит. Поэтому
 *  здесь не соседство, а просто оба слова где-то в одном сообщении: в этом
 *  боте «рецепт» рядом с просьбой прислать значит ровно одно. */
const SEND_VERB = rx([
  "равон|фирист|бифирист|бде(д|ҳед)?|диҳед|дихед|дайте|скинь|пришли|отправьте|покажите|поделитесь",
]);

export function detectMenuQuestion(text: string): boolean {
  const trimmed = text.trim();
  if (trimmed.length < 3) return false;
  if (MENU_WORDS.test(trimmed)) return true;
  return /рецепт/iu.test(trimmed) && SEND_VERB.test(trimmed);
}

