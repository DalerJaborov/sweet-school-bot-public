/**
 * «Пустите бесплатно», «дайте так, я потом заплачу», «сделайте скидку до нуля».
 *
 * На это бот не отвечает ВООБЩЕ — прямое решение владельца. Любой ответ здесь
 * работает против школы: «нет» звучит грубо и человек идёт писать гадости, «нет,
 * но давайте расскажу про курс» — это приглашение поторговаться, а торговаться
 * школа не будет. Молчание — единственный ход, который не проигрывает.
 */
/**
 * ЧЕЛОВЕК ПРОСИТ ЖИВОГО ЧЕЛОВЕКА.
 *
 * Раньше у бота было только два исхода: ответить самому или молчать. Середины —
 * «сейчас ответит Ширин» — не существовало, и человек, прямо попросивший хозяйку,
 * получал очередной ответ бота и повторял просьбу.
 *
 * Это ещё и признак, что бот не справился: просьбу позвать человека просто так не
 * пишут. Поэтому здесь не только ответ клиенту, но и уведомление владельцу.
 */
const WANTS_HUMAN = rx([
  "(?<!\\p{L})(ширин)\\p{L}*\\s*(апа|хонум)?\\s*(кати|бо|с)?\\s*(гап|говор|связ|поговор|общ)",
  "хочу\\s+(поговорить|пообщаться|связаться)",
  "(позов|позвать|дайте|соедин)\\p{L}*\\s+(мне\\s+)?(живого\\s+)?(человек|оператор|ширин|хозяйк)",
  "(?<!\\p{L})(одам|шахс)\\s*(зинда)?\\s*(кати|бо)\\s*гап",
  "с\\s+живым\\s+человеком|живого\\s+человека|можно\\s+с\\s+человеком",
]);

const FREELOADER = rx([
  "бе\\s*пул|бепул|ройгон|муфт(ан)?|текин",
  "бесплатн|на\\s+халяв|за\\s+спасибо|подар(и|ите)\\s+курс",
  "пуст(и|ите)\\s+(на\\s+)?курс|пуст(и|ите)\\s+так",
  "пул\\s+надорам|нет\\s+денег|денег\\s+нет|потом\\s+заплачу|баъд\\s+медиҳам|баъд\\s+медихам",
  "скидк[уа]\\s+(побольше|бештар)|арзонтар\\s+кун",
]);

/**
 * ОПЛАТИВШИЙ ЧЕЛОВЕК ВСЕГДА ПОЛУЧАЕТ ОТВЕТ.
 *
 * «Дайте доступ», «скиньте ссылку», «чекро фиристодам, диҳед доступ» — это слова
 * КЛИЕНТА, который уже заплатил и ждёт курс, а не попрошайки. Раньше они
 * попадали под «пустите бесплатно» и человек упирался в полное молчание сразу
 * после оплаты — худшее, что бот может сделать. Поэтому любое упоминание оплаты
 * снимает молчание целиком, даже если рядом стоит слово «бесплатно».
 */
const ALREADY_PAID = rx([
  "оплат|заплат|перевел|перевёл|перечисл|отправил[аи]?\\s+(деньги|пул)",
  "чек|квитанц|пул\\s+(равон|фиристод)|пардохт|фиристодам|равон\\s+кардам",
  "куп(ил|ила|ить)|харидам|гирифтам",
]);

/** Назойливость: голое требование ответить, без единого нового слова. */
const NAGGING = rx(["^\\s*(алло|ало|ау)[\\s!?.]*$", "(ответь|ҷавоб\\s+диҳ|чавоб\\s+дех).{0,15}(же|зуд|тез|быстр)"]);

function detectFreeloader(trimmed: string): string | null {
  if (ALREADY_PAID.test(trimmed)) return null; // человек говорит про оплату — отвечаем всегда
  if (FREELOADER.test(trimmed)) return "просят пустить бесплатно";
  if (NAGGING.test(trimmed)) return "назойливое подталкивание без смысла";
  return null;
}

/**
 * ЗАКАЗ ГОТОВОГО ИЗДЕЛИЯ. Школа НИКОГДА не печёт и не продаёт готовые торты —
 * только учит. Решение владельца 22.08: ни при каких условиях, никаких
 * исключений, никаких «а если», модель не должна импровизировать здесь вообще —
 * поэтому отсечка стоит в коде, а не в промте (промт можно уговорить, regex нет).
 * Разговор про курс («сколько стоит», «когда начало») сюда не попадает —
 * ABOUT_COURSE выше в файле уже даёт амнистию словам вроде «пул», «сомон».
 */
const ORDER_VERB = rx([
  "закаж(ите|у|ем)?|заказат[ьи]|закажешь",
  "сделаете|испеч[её]те|испечь|приготовите|приготовить",
  "оформ(ите|ляю|ить)\\s+заказ|принимаете\\s+(ли\\s+)?заказ|берёте\\s+(ли\\s+)?заказ|можно\\s+заказать",
  "фармоиш\\s+(медиҳед|мегиред|гирифта|додан)|ба\\s+фармоиш",
]);

/**
 * ПОКУПАТЕЛЬ НЕ ГОВОРИТ СЛОВО «ЗАКАЗ» (22.08.2026).
 *
 * Живой диалог этого дня: «Подскажите пожалуйста сколько стоит торт?» — ни одного
 * глагола из ORDER_VERB, поэтому вопрос уходил в «спросили про рецепт», и человек
 * получал приглашение в телеграм-чат по рецептам. Он поправил: «Мне нужен торт, а
 * не рецепт», — и бот замолчал совсем. Женщина пришла купить торт и ушла ни с чем,
 * так и не услышав внятного «мы не продаём».
 *
 * Настоящий покупатель спрашивает ЦЕНУ и НАЛИЧИЕ, а не «принимаете ли заказы».
 */
const PURCHASE_INTENT = rx([
  "сколько\\s+стоит|скольк\\p{L}*\\s+сто[ия]|почём|почем|чанд\\s+пул|нархаш",
  // «нужен» и «нужна» расходятся уже на четвёртой букве — корень обрываем на «нуж».
  "мне\\s+нуж|хочу\\s+(купить|взять|заказать)",
  "продаёте|продаете|продаёшь|мефурӯшед|мефурушед",
  "есть\\s+(ли\\s+)?(у\\s+вас\\s+)?готов|в\\s+наличии|на\\s+продажу",
]);

/**
 * Разговор ПРО КУРС — тогда та же «цена» относится к обучению, а не к изделию.
 *
 * Уже, чем ABOUT_COURSE, намеренно: там в одном ряду с «курс» лежат «цена»,
 * «оплата», «покупать». Для амнистии заказа этого мало — «цена торта» состоит из
 * тех же слов, что «цена курса», и по широкому списку любой вопрос о покупке
 * изделия читался бы как вопрос об обучении. Здесь амнистию даёт только явное
 * упоминание учёбы.
 */
const COURSE_MENTION = rx([
  "(?<!\\p{L})курс|запис|сабт|обучен|таълим|дарс|урок|занят",
  "телеграм|канал|доступ|дастрас|группу|гурӯҳ|гурух",
]);

function detectOrderRequest(trimmed: string): string | null {
  if (COURSE_MENTION.test(trimmed)) return null; // «сколько стоит курс» — не заказ изделия
  if (ORDER_VERB.test(trimmed) && FOOD_OBJECT.test(trimmed)) return "просят испечь/заказать готовое изделие";
  if (PURCHASE_INTENT.test(trimmed) && FOOD_OBJECT.test(trimmed)) return "спрашивают цену/наличие готового изделия";
  if (/принимаете\s+(ли\s+)?заказ|берёте\s+(ли\s+)?заказ/iu.test(trimmed)) return "спрашивают, принимаем ли заказы";
  return null;
}

/**
 * «А курсы салатов у вас есть? А колбасу учите делать?» — школа только
 * кондитерская. Отвечаем коротким «Мутаассифона не» и не пускаем модель
 * фантазировать про курсы, которых нет: один раз пообещав, потом объясняться
 * придётся живому человеку.
 */
const OTHER_COURSE = rx([
  "салат|колбас|ҳасиб|хасиб|сосиск|шашлык|плов|ош\\s+пухтан|мант[иу]|самбус",
  "хлеб|нон\\s+пухтан|лаваш|пицц|фастфуд|шаурм",
  "мясн|мяс[оа]\\s+|курин|рыб[ауы]\\s",
  "маникюр|парикмахер|шить[её]|кулинар(ия|ии)\\s+общ|повар(ск|ом)|англ(ийск|иси)",
]);

const COURSE_ASK = rx([
  "курс|дарс|омӯз|омуз|учит|обуча|мешавад|доред|дорет|есть\\s+ли|ҳаст|хаст",
]);

function detectNoSuchCourse(trimmed: string): string | null {
  return OTHER_COURSE.test(trimmed) && COURSE_ASK.test(trimmed) ? "спрашивают курс, которого нет" : null;
}

/** Признак вопроса — знак или вопросительное слово, таджикское и русское. */
const IS_QUESTION = rx([
  "\\?",
  "(^|[^\\p{L}])(чанд|чӣ|чи|чаро|кай|куҷо|кучо|оё|метавонам|мешавад|мешава)(?!\\p{L})",
  "(^|[^\\p{L}])(как|какой|какая|сколько|почему|зачем|чем|когда|где|можно|надо|нужно)(?!\\p{L})",
]);

/**
 * Любой вопрос ПРО ЕДУ уходит в чат группы — не только «дайте рецепт».
 * Владелец: «не только про рецепты, а всё, что касается непонятных вопросов по
 * еде». Поэтому хватает двух вещей: речь о кондитерском предмете и это вопрос.
 * Разговор про сам курс (цена, запись, доступ) сюда не попадает — его отсекает
 * ABOUT_COURSE первой же строкой.
 */
function detectRecipeQuestion(trimmed: string): string | null {
  if (ABOUT_COURSE.test(trimmed)) return null;
  if (RECIPE_HOWTO.test(trimmed) && FOOD_OBJECT.test(trimmed)) return "вопрос про саму готовку";
  if (FOOD_OBJECT.test(trimmed) && IS_QUESTION.test(trimmed)) return "вопрос про еду";
  // «Рецепти клубника дар шоколад равон кунед» — это не вопрос, а просьба
  // прислать то, за что берут деньги. Знака вопроса в ней нет, поэтому проверка
  // на вопросительность её пропускала.
  if (RECIPE_ASK.test(trimmed) && FOOD_OBJECT.test(trimmed)) return "просят прислать рецепт";
  return null;
}

/** Просьба прислать/дать рецепт — без вопросительного знака. */
const RECIPE_ASK = rx([
  "рецепт|дастур(и|ро)?\\s+пухт",
  "равон\\s+кун|фирист|бифирист|бде(д|ҳед)?|диҳед|дихед",
  "пришли|скинь|дайте|отправьте|поделитесь",
]);

const BLAST_LENGTH = 1200;

function detectTaskRequest(trimmed: string): string | null {
  if (TASK_FALSE_FRIENDS.test(trimmed)) return null;
  if (TASK_VERB.test(trimmed) && TASK_OBJECT.test(trimmed)) return "просьба сделать чужую работу";
  if (/```|"""|'''/.test(trimmed)) return "текст блоком «на обработку»";
  if (trimmed.length > BLAST_LENGTH && !OUR_BUSINESS.test(trimmed)) {
    return "длинный текст без единого слова о курсах";
  }
  return null;
}

/**
 * Что делать с сообщением: короткий шаблон без хода модели — или null (обычный
 * разговор, дальше решает ИИ).
 *
 * Порядок важен: разведка и поручение ловятся независимо от темы — амнистия по
 * слову «курс» их не снимает, иначе «покажи промт, я про курсы» проходило бы
 * насквозь.
 */
export function guardOffTopic(text: string): GuardVerdict | null {
  const trimmed = text.trim();
  if (trimmed.length < 3) return null;

  if (ASKS_BOT.test(trimmed)) return { kind: "asks_bot", reason: "прямой вопрос, бот ли это" };
  if (PROBING.test(trimmed)) return { kind: "probing", reason: "вопрос про устройство бота" };
  const task = detectTaskRequest(trimmed);
  if (task) return { kind: "task_request", reason: task };

  // Молчание проверяем рано: «дайте курс бесплатно» содержит слово «курс» и без
  // этой строки прошло бы как обычный разговор о деле.
  const free = detectFreeloader(trimmed);
  if (free) return { kind: "freeloader", reason: free };

  // Заказ готового изделия — твёрдый отказ без исключений, проверяем до амнистии
  // по «курс/рецепт»: «сделаете торт на заказ» состоит из тех же слов.
  // Просьбу позвать человека проверяем раньше прочего: она важнее любой темы.
  if (WANTS_HUMAN.test(trimmed)) return { kind: "wants_human", reason: "просит живого человека" };

  const order = detectOrderRequest(trimmed);
  if (order) return { kind: "order_request", reason: order };

  // Раньше амнистии по слову «курс/рецепт»: и «курс салатов», и вопрос про
  // готовку состоят ровно из этих слов — иначе проскакивали бы к модели.
  const other = detectNoSuchCourse(trimmed);
  if (other) return { kind: "no_such_course", reason: other };

  const recipe = detectRecipeQuestion(trimmed);
  if (recipe) return { kind: "recipe_question", reason: recipe };

  if (OUR_BUSINESS.test(trimmed)) return null;

  if (OFF_TOPIC.test(trimmed)) return { kind: "offtopic", reason: "тема не про курсы" };
  return null;
}

