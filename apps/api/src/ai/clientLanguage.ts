export type ClientLanguage = "ru" | "tg" | "en";

/**
 * НА КАКОМ ЯЗЫКЕ ПИШЕТ ЧЕЛОВЕК.
 *
 * ПОЧЕМУ НЕ ХВАТАЕТ ОДНИХ БУКВ. Раньше здесь стояла единственная проверка: есть в
 * тексте ӣӯҳқҷғ — значит таджикский, нет — русский. Беда в том, что в Душанбе
 * половина пишет обычной кириллицей, без этих букв вовсе. Живая переписка
 * 22.08.2026: «Курси Салат Доред», «Сливкаш Чи намуд бошад Ман нофахмидам» — ни
 * одной особой буквы, и бот отвечал таджикоязычной женщине по-русски: «Мутаассифона
 * не, апачон — у нас только кондитерские курсы». Половина фразы на её языке,
 * половина на чужом — так живой человек не пишет никогда.
 *
 * Поэтому язык узнаётся по СЛОВАМ, а буквы остаются самым сильным признаком.
 * Список короткий и намеренно из служебных слов — местоимения, вопросительные,
 * связки: они встречаются в любой фразе и не зависят от темы разговора.
 */
const TAJIK_LETTERS = /[ӣӯҳқҷғ]/i;

/**
 * Частые таджикские слова БЕЗ особых букв — как их набирают с обычной клавиатуры.
 * Границы слова обязательны: «ман» внутри «манго» или «команда» ничего не значит.
 */
const TAJIK_WORDS = new RegExp(
  "(?<!\\p{L})(" +
    "ман|шумо|туро|худам|худатон|" +
    "чихел|чи хел|чанд|кадом|кай|" +
    "доред|дорем|дорад|дорам|мешавад|мешад|мешан|мекунем|мекунад|мекнем|мекнен|мекунен|кунед|" +
    "бошад|бошем|хаст|нест|" +
    "апачон|апаҷон|ападжон|хохарам|" +
    "ассалом|салом|рахмат|раҳмат|бале|" +
    "барои|хамин|ҳамин|хеле|зиёд|" +
    "нархаш|сомони|" +
    "мехохам|мехоҳам|нофахмидам|нафахмидам|фахмидам|мефахмонем|" +
    "курси|дарсхо|дарсҳо|тайёр|интизор" +
    ")(?!\\p{L})",
  "iu"
);

/**
 * Таджикский ЛАТИНИЦЕЙ — «Salom apajon», «chi hel», «narkhash chand».
 *
 * Так пишут с телефона, где не переключили раскладку. Без этого списка латиница
 * автоматически считалась бы английским (или русским), и человек получал бы ответ
 * на чужом языке — та же беда, что была с кириллицей без особых букв.
 */
const TAJIK_LATIN = new RegExp(
  "(?<!\\p{L})(" +
    "salom|assalom|apajon|apachon|rahmat|" +
    "chi|chihel|chi hel|chand|kadom|" +
    "dored|dorem|dorad|meshavad|meshad|mekunem|" +
    "narkh|narkhash|somoni|man|shumo|hub|bale" +
    ")(?!\\p{L})",
  "iu"
);

/** Латинские служебные слова — тот же приём для английского. */
const ENGLISH_WORDS = new RegExp(
  "(?<!\\p{L})(" +
    "hello|hi|hey|please|thanks|thank|sorry|" +
    "how|what|when|where|why|which|who|" +
    "the|and|for|you|your|my|we|is|are|do|does|can|could|would|want|need|" +
    "price|cost|course|online|offline|lesson|cake|dessert|order|buy" +
    ")(?!\\p{L})",
  "iu"
);

/** Есть ли кириллица вообще — латиница без неё это уже не «русский без букв». */
const CYRILLIC = /\p{Script=Cyrillic}/u;

/**
 * ЯЗЫК СЧИТАЕТСЯ ПО КАЖДОМУ СООБЩЕНИЮ ОТДЕЛЬНО — намеренно.
 *
 * Решение владельца 22.08.2026: «если посреди разговора человек переключается на
 * другой язык, отвечать сразу на языке клиента — как живой человек». Поэтому здесь
 * нет памяти о прошлом выборе: на что человек перешёл, на том и отвечаем.
 *
 * Пустой текст — таджикский: это язык школы по умолчанию, и на нём же написана
 * воронка. Отвечать по-русски человеку, о котором мы ничего не знаем, — ошибка
 * в сторону чужого языка, а не своего.
 */
export function detectClientLanguage(text: string): ClientLanguage {
  const value = (text ?? "").trim();
  if (!value) return "tg";

  // Особые буквы — признак, который не подделаешь: они есть только в таджикском.
  if (TAJIK_LETTERS.test(value)) return "tg";
  if (TAJIK_WORDS.test(value)) return "tg";

  // Латиница: сначала таджикская, потом английская — «Salom apajon» это не English.
  if (!CYRILLIC.test(value) && TAJIK_LATIN.test(value)) return "tg";
  if (!CYRILLIC.test(value) && ENGLISH_WORDS.test(value)) return "en";

  return "ru";
}

/**
 * НА КАКОМ ЯЗЫКЕ ОТВЕТИЛА МОДЕЛЬ — отдельный, более строгий детектор.
 *
 * Живой прогон 05.09.2026: на 4–6-е русское сообщение подряд бот отвечал
 * по-таджикски («Кабул кардем апачон, хозир дохил мекнем»), и промт этого не
 * удержал. Проверять ответ тем же detectClientLanguage нельзя: русский ответ
 * бота по замыслу содержит «апачон», «сомони», «Ширин», и одно такое слово
 * сразу дало бы «таджикский» — бот перегенерировал бы каждый второй ответ.
 *
 * Поэтому здесь: особые буквы — таджикский без вопросов; иначе нужны ДВА
 * разных таджикских служебных слова, а обращения и общие слова (апачон,
 * сомони, салом, рахмат) не считаются вовсе. Один случайный таджикизм в
 * русской фразе — ещё русский; два — уже другой язык.
 */
const TAJIK_REPLY_WORDS = new RegExp(
  "(?<!\\p{L})(" +
    "ман|мо|шумо|худам|худатон|инро|онро|" +
    "чихел|чи хел|чанд|кадом|кай|чаро|" +
    "доред|дорем|дорад|дорам|мешавад|мешад|мешан|мекунем|мекунад|мекнем|мекнен|мекунен|мекунам|кунед|кардем|кардам|" +
    "бошад|бошем|хаст|ҳаст|нест|аст|" +
    "барои|хамин|ҳамин|хеле|зиёд|хозир|ҳозир|дохил|кабул|қабул|албатта|" +
    "мехохам|мехоҳам|метавонед|метавонам|фиристед|нависед|бинед|гиред|" +
    "медихам|медиҳам|медиханд|медиҳанд|мебинам|мефиристам|мегуям|мегӯям|ҷавоб|чавоб|" +
    // Изафет и объектный «-ро» — грамматика, которой в русском нет: «чекро», «нархаш».
    "чекро|пулро|чекаша|нархаш|нархи|" +
    "курси|дарсхо|дарсҳо|дарс|тайёр|интизор|пардохт|пайванд|нарх" +
    ")(?!\\p{L})",
  "giu"
);

export function detectReplyLanguage(text: string): ClientLanguage {
  const value = (text ?? "").trim();
  if (!value) return "tg";
  // Латиница: английские служебные слова важнее — «somoni» есть в любом языке ответа.
  if (!CYRILLIC.test(value)) {
    if (ENGLISH_WORDS.test(value)) return "en";
    return TAJIK_LATIN.test(value) ? "tg" : "en";
  }
  if (TAJIK_LETTERS.test(value)) return "tg";
  const distinct = new Set<string>();
  for (const m of value.matchAll(TAJIK_REPLY_WORDS)) distinct.add(m[1].toLowerCase());
  return distinct.size >= 2 ? "tg" : "ru";
}
