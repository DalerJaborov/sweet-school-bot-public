/**
 * Личные контакты хозяйки — мама, сестра, тётя, подруги. С ними бот не должен
 * разговаривать ВООБЩЕ: это не клиенты, а живая переписка семьи, и «здравствуйте,
 * какой курс вас интересует?» в ответ на «дочка, ты покушала?» — позор.
 *
 * Ловим по обращению, а не по теме: родственные слова в первом же сообщении —
 * почти безошибочный признак, а тему разговора родня может завести любую.
 * Промахнуться в другую сторону (принять клиента за родню) не страшно: владелец
 * видит список в панели и снимает отметку одной кнопкой.
 */

const rx = (parts: string[]): RegExp => new RegExp(parts.join("|"), "iu");

/** Обращения, которых от клиента не бывает. */
const FAMILY = rx([
  // Русский
  "(?<!\\p{L})(доченьк|дочк|дочен|сынок|мамочк|мамуль|мам(а|е|у|ы)?)(?!\\p{L})",
  "(?<!\\p{L})(сестрёнк|сестрен|сестричк|братишк|тётя|тетя|тётушк|бабушк|дедушк|племянниц)(\\p{L}*)?(?!\\p{L})",
  "(?<!\\p{L})(ападжон|апажон|апаҷон)(?!\\p{L})",
  // Таджикский: мать/сестра/тётя/дочь + ласкательные формы
  "(?<!\\p{L})(модар|модарҷон|модарчон|очаҷон|очачон|оча)(\\p{L}*)?(?!\\p{L})",
  "(?<!\\p{L})(хоҳар|хохар|хоҳарҷон|хохарчон|апа|апаҷон)(\\p{L}*)?(?!\\p{L})",
  "(?<!\\p{L})(амма|хола|бибӣ|биби|додар|духтарам|писарам)(\\p{L}*)?(?!\\p{L})",
]);

/** Бытовые семейные фразы — второй признак, чтобы не ловить «сестрёнка» в
 *  вежливом обращении клиентки к другой клиентке под постом. */
const HOUSEHOLD = rx([
  "хуб\\s+ҳастӣ|хуб\\s+хасти|чӣ\\s+хел\\s+ҳастӣ|чи\\s+хел\\s+хасти",
  "хӯрок\\s+хӯрдӣ|хурок\\s+хурди|нон\\s+хӯрдӣ|шом\\s+хӯрдӣ",
  "кай\\s+меоӣ|кай\\s+меои|дар\\s+хона|ба\\s+хона\\s+биё",
  "ты\\s+(поела|покушала|дома|приедешь)|как\\s+(дела|ты\\s+там)|когда\\s+приедешь",
  "позвони\\s+мне|перезвони",
]);

/** true — почти наверняка личная переписка, а не клиент. */
export function looksPersonal(text: string): boolean {
  const trimmed = text.trim();
  if (trimmed.length < 3) return false;
  // Оба признака вместе: одно родственное слово может встретиться и у клиентки
  // («апа, салом»), а вот вместе с бытовым вопросом — это уже точно родня.
  return FAMILY.test(trimmed) && HOUSEHOLD.test(trimmed);
}

/** Первое слово — обращение к родне. Клиентки так не начинают: «мама, ты где?», «доченька, привет». */
const FAMILY_ADDRESS_FIRST = /^[\s\p{P}\p{S}]*(мама|мамочка|мамуль|мамуля|доченька|дочка|дочь|сынок|сыночек|бабушка|бабуля|дедушка|тётя|тетя|сестрёнка|сестренка|братишка|модарҷон|модарчон|духтарам|писарам|додарҷон|хоҳарҷон|хохарчон)(?=[\s\p{P}\p{S}]|$)/iu;

/**
 * Надёжный отлов родни по ПЕРВОМУ сообщению: оно начинается с обращения к родне.
 * Обращение в середине фразы («моя мама хочет на курс») сюда не попадает — только начало.
 * «Апа» намеренно нет: так клиентки обращаются к самой Ширин.
 */
export function startsWithFamilyAddress(text: string): boolean {
  const t = text.trim();
  return t.length >= 2 && FAMILY_ADDRESS_FIRST.test(t);
}
