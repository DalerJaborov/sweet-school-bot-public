/**
 * «НЕ ПО ДЕЛУ — МОЛЧАТЬ» (решение владельца 08.11.2026).
 *
 * Реклама ведёт в личку и в WhatsApp, куда пишут не только покупательницы, но и
 * знакомые, курьеры, магазины, поставщики. Ответ бота «какой курс вас интересует?»
 * курьеру или подруге хозяйки — позор для неё. Поэтому перед ответом НОВОМУ
 * собеседнику сообщение разбирается по классам, и отвечаем только «по делу».
 *
 * ДВЕ ЗАЩИТЫ (как везде в проекте):
 *  1) код: codeRelevance — бесплатные правила, решают очевидное без модели;
 *  2) модель: дешёвая flash-lite со структурным ответом — только для неочевидного.
 * Сам промт ответа тоже знает правило «не по делу — [NO_REPLY]» (ALWAYS_RULES).
 *
 * Модуль чистый: вызов модели передаётся снаружи (deps.generate). Так его можно
 * гонять в тестах без сети и на корпусе — тем же кодом, что работает в бою.
 */

export type RelevanceClass =
  | "on_topic" //  курсы, цена, оплата, чек, рецепты, запись, доступ, реклама
  | "greeting" //  только «салом»/«привет» — типичный заход с рекламы
  | "personal" //  знакомый, родня, личное
  | "delivery" //  курьер, доставка, водитель
  | "shop" //      магазин, поставщик, чужая реклама, продажи нам
  | "spam" //      спам, ссылки, мусор
  | "empty" //     стикер, смайлик, пусто
  | "unclear"; //  непонятно, к чему

export const RELEVANCE_CLASSES: readonly RelevanceClass[] = [
  "on_topic",
  "greeting",
  "personal",
  "delivery",
  "shop",
  "spam",
  "empty",
  "unclear",
];

export interface RelevanceVerdict {
  cls: RelevanceClass;
  /** code — решили правила; model — решила модель; fallback — модель недоступна. */
  source: "code" | "model" | "fallback";
  /** Одна короткая причина — попадает в журнал, чтобы хозяйка видела, почему молчали. */
  reason: string;
}

export type RelevanceAction = "reply" | "clarify" | "attention" | "silent";

/** Отвечаем по сути только на эти классы. */
export const ANSWERABLE: ReadonlySet<RelevanceClass> = new Set(["on_topic", "greeting"]);

const rx = (parts: string[]): RegExp => new RegExp(parts.join("|"), "iu");
const NB = "(?<![\\p{L}\\p{N}])";
const NE = "(?![\\p{L}\\p{N}])";

/** Слова, которые бывают почти только у покупательницы курса. */
const STRONG_COURSE = rx([
  `${NB}(курс|курсы|курсов|курсу|курсе|курси|курсҳо|курсхо|урок|уроки|рецепт|рецепты|рецепти|рецептҳо|дарс|дарсхо|дарсҳо)${NE}`,
  `${NB}(оплат|оплач|чек|чеки|квитанц|реквизит|перевела|перевёл|пардохт|чекро)\\p{L}*`,
  `${NB}(сертификат|обучени|обучать|научит|научиться|ёд\\s*гир|ед\\s*гир|омӯз|омуз)\\p{L}*`,
  `${NB}(арт[\\s-]*десерт|21\\s*рецепт|дар\\s+назди\\s+ман|назди\\s+худат)${NE}`,
  `${NB}(ссылк\\p{L}*\\s+на\\s+(курс|урок|группу)|доступ\\p{L}*\\s+(к|ба)\\s+курс)`,
  `${NB}(сколько\\s+стоит\\s+(курс|обучение)|нархи\\s+курс|курс\\s+чанд)`,
]);

/** Курьер, водитель, доставка заказа. */
const DELIVERY = rx([
  `${NB}(курьер|курер|курйер|водител|доставщик|таксист|экспедитор)\\p{L}*`,
  `${NB}(доставк\\p{L}*|доставил\\p{L}*|привез\\p{L}*|привёз\\p{L}*|подъезжа\\p{L}*|подъехал\\p{L}*)`,
  `${NB}(заберите|заберёте|заберете|забирать)\\s+(посылк|заказ|груз)`,
  `${NB}(посылк|накладн|трек[\\s-]*номер|груз)\\p{L}*`,
  `${NB}(борхалта|супориш|расонид|расонам)\\p{L}*`,
  `${NB}(внизу|у\\s+входа|у\\s+дверей|у\\s+подъезда|во\\s+дворе)${NE}`,
]);

/** Магазин, поставщик, чужое предложение («купите у нас», «оптом», «прайс»). */
const SHOP = rx([
  `${NB}(поставщик|поставк|оптом|прайс|партию|партия)\\p{L}*`,
  `${NB}(наш\\s+магазин|наша\\s+компания|наш\\s+склад|наше\\s+предложение|предлагаем|предлагаю\\s+(вам\\s+)?(купить|услуг|сотруднич))`,
  `${NB}(коммерческ\\p{L}*\\s+предложени|сотрудничеств|партн[её]рств)`,
  `${NB}(ваш\\s+заказ\\s+(готов|собран|ожидает)|в\\s+наличии\\s+на\\s+складе|товар\\p{L}*\\s+в\\s+наличии)`,
  `${NB}(магазин|фурӯшгоҳ|мағоза|мағоздор|таъминкунанда)\\p{L}*`,
]);

/** Явный спам и мусор. */
const SPAM = rx([
  `(https?://|www\\.)\\S+\\.(xyz|top|click|loan|bet|win)\\b`,
  `${NB}(казино|ставки\\s+на\\s+спорт|букмекер|заработок\\s+без\\s+вложений|быстрый\\s+заработок|кредит\\s+без\\s+справок|займ\\s+онлайн)`,
  `${NB}(вы\\s+выиграли|ваш\\s+приз|перейдите\\s+по\\s+ссылке\\s+и\\s+получите)`,
]);

/** Личное: обращение к «дочке», «сестре», бытовой вопрос, поздравление. */
const PERSONAL = rx([
  `${NB}(дочк\\p{L}*|доченьк\\p{L}*|сынок|мамочк\\p{L}*|мамуль\\p{L}*|сестрёнк\\p{L}*|сестренк\\p{L}*|племянниц\\p{L}*)${NE}`,
  `${NB}(как\\s+(дела|ты\\s+там|здоровье|самочувствие)|ты\\s+(поела|покушала|дома|приедешь)|когда\\s+приедешь|во\\s+сколько\\s+придёшь)`,
  `${NB}(с\\s+днём\\s+рождения|поздравляю\\s+с\\s+днём|с\\s+праздником)`,
  `${NB}(хуб\\s+ҳастӣ|хуб\\s+хасти|чӣ\\s+хел\\s+ҳастӣ|хӯрок\\s+хӯрдӣ|кай\\s+меоӣ|ба\\s+хона\\s+биё)`,
  `${NB}(позвони\\s+мне|перезвони|занг\\s+зан)`,
]);

/** Одно приветствие и больше ничего. */
const GREETING_ONLY = new RegExp(
  `^[\\s\\p{P}\\p{S}]*(салом|салам|ассалом|ассалому\\s+алайкум|ассалому\\s+алейкум|ассалам\\p{L}*|воалайкум\\p{L}*|воалекум\\p{L}*|ва[\\s-]*а?(лайкум|лейкум|ликум|лекум)\\p{L}*(\\s+(ассалом|салом|ассалому))?|привет|приветствую|здравствуйте|здравствуй|добрый\\s+(день|вечер|утро)|доброе\\s+утро|хай|hi|hello|hey|salom|assalom\\p{L}*|salam|privet|рӯз\\s+ба\\s+хайр|субҳ\\s+ба\\s+хайр|шом\\s+ба\\s+хайр)[\\s\\p{P}\\p{S}]*(апачон|апа|апаҷон|хоҳарҷон|хохарчон|ширин|ширинхон)?[\\s\\p{P}\\p{S}]*$`,
  "iu",
);

/** Нет ни одной буквы и цифры — смайлик, точка, стикер. */
function hasNoContent(text: string): boolean {
  return !/[\p{L}\p{N}]/u.test(text);
}

/**
 * Бесплатные правила. null — правила не решили, нужна модель.
 *
 * Порядок важен: сначала «явно наше дело», потом «явно чужое». Если в одном
 * сообщении и то и другое («курьер, где мой чек») — это уже наше дело, молчать нельзя.
 */
export function codeRelevance(textRaw: string, hasMedia = false): RelevanceVerdict | null {
  const text = (textRaw ?? "").trim();
  // «+» в ответ на рекламу («напишите + в директ») — это покупательница, а не пустота.
  if (/^[+＋]+$/.test(text)) return { cls: "greeting", source: "code", reason: "плюс в ответ на рекламу" };
  if (!text || hasNoContent(text)) {
    return hasMedia ? null : { cls: "empty", source: "code", reason: "пустое сообщение, стикер или смайлик" };
  }
  if (GREETING_ONLY.test(text)) return { cls: "greeting", source: "code", reason: "только приветствие" };
  if (STRONG_COURSE.test(text))
    return { cls: "on_topic", source: "code", reason: "в тексте слова про курс или оплату" };
  if (SPAM.test(text)) return { cls: "spam", source: "code", reason: "признаки спама" };
  // Курьера, личное и магазин правила НЕ решают сами (ревью 08.11.2026): «Торт с доставкой сколько?»,
  // «Салом апа, как дела?», «У вас есть магазин?» — это покупательницы. Молчание решает модель
  // с историей переписки; правила дают ей только подсказку (см. suspectedClass).
  return null;
}

/** Подозрение правил — не решение, а подсказка модели. */
export function suspectedClass(text: string): RelevanceClass | null {
  if (DELIVERY.test(text)) return "delivery";
  if (PERSONAL.test(text)) return "personal";
  if (SHOP.test(text)) return "shop";
  return null;
}

export const RELEVANCE_PROMPT = `Ты фильтр входящих сообщений кондитерской школы Shirin Sweets (Душанбе, Таджикистан).
Школа учит печь десерты: онлайн-курсы «21 рецепт» и «Арт-десерты» и очный курс. Хозяйка школы — Ширин. Готовые торты школа НЕ продаёт.
Сообщения приходят в Instagram, WhatsApp и чат сайта, на русском, таджикском (кириллицей, часто без спецбукв: «хохарчон», «апачон», «чанд сом») или смесью.
Определи, к какому классу относится ПОСЛЕДНЕЕ сообщение собеседника. Предыдущие реплики даны только для контекста.

Классы:
- on_topic: про курсы, цену, оплату, чек, рецепты, десерты, запись на курс, доступ к урокам, рекламу школы, вопрос покупательницы о школе. Также вопрос про готовый торт на заказ: человек пришёл как клиент, это по делу (бот вежливо откажет).
- greeting: приветствие без темы, в том числе вежливое «как дела / хубй / созен / хуб ҳастед» и обращение «апа, апачон, Ширин». Так пишут и покупательницы, это НЕ личное.
- personal: ТОЛЬКО явно личное, не про школу: обращение к родне («мама, дочка»), поздравление с днём рождения или праздником, «позвони мне», договорённость о встрече, семейные новости. Обращение «апа/апачон/Ширин» и вежливые вопросы про здоровье — НЕ повод считать личным.
- delivery: курьер, водитель, доставка, посылка, «я у подъезда».
- shop: магазин, поставщик, оптовик, чужая реклама, предложение что-то купить или сотрудничать.
- spam: спам, ссылки на посторонние сайты, казино, заработок, мусор.
- Вопрос, где находится школа, где живёт Ширин, куда приходить — on_topic (очный курс).
- Благодарность Ширин за урок, отзыв, курс («Рахмат апа барои отзыв») — on_topic.
- unclear: непонятно, к чему сообщение, и нельзя сказать, клиент это или нет (одно слово «да», «ок», «скажите», обрывок).

Правила:
1. Сомневаешься между on_topic и чужим классом — выбирай unclear, не угадывай.
2. Если в сообщении есть вопрос о школе или курсах — on_topic, даже с ошибками и на таджикском.
3. Кнопки и подписи из рекламы («ОНЛАЙН 21 РЕЦЕПТ», «ДАР НАЗДИ МАН», «ХАРИДАНИ КУРС») — on_topic.
4. Ответь ТОЛЬКО JSON: {"cls":"<класс>","reason":"<до 8 слов по-русски>"}.

Примеры:
«Салом, нархи курс чанд?» -> {"cls":"on_topic","reason":"спрашивает цену курса"}
«Я курьер, выйдите заберите заказ» -> {"cls":"delivery","reason":"курьер просит забрать заказ"}
«Здравствуйте, предлагаем муку оптом по низким ценам» -> {"cls":"shop","reason":"поставщик предлагает товар"}
«Дочка, ты покушала? Когда приедешь?» -> {"cls":"personal","reason":"семейное обращение"}
«Ширин, с днём рождения тебя!» -> {"cls":"personal","reason":"личное поздравление"}
«Скажите пожалуйста» -> {"cls":"unclear","reason":"нет предмета вопроса"}
«Торт на заказ на субботу сколько?» -> {"cls":"on_topic","reason":"клиент спрашивает торт"}`;

/** Разбор ответа модели. null — не JSON или класс неизвестен: такому ответу верить нельзя. */
export function parseRelevance(raw: string | null | undefined): { cls: RelevanceClass; reason: string } | null {
  if (!raw) return null;
  const cleaned = raw.replace(/```(?:json)?/gi, "").trim();
  const start = cleaned.indexOf("{");
  const end = cleaned.lastIndexOf("}");
  if (start < 0 || end <= start) return null;
  try {
    const parsed = JSON.parse(cleaned.slice(start, end + 1)) as { cls?: unknown; reason?: unknown };
    const cls = String(parsed.cls ?? "").trim() as RelevanceClass;
    if (!RELEVANCE_CLASSES.includes(cls)) return null;
    const reason = typeof parsed.reason === "string" ? parsed.reason.slice(0, 120) : "";
    return { cls, reason };
  } catch {
    return null;
  }
}

export interface RelevanceDeps {
  /** Вызов дешёвой модели: системный промт + одно сообщение; возвращает текст или null. */
  generate: (system: string, user: string) => Promise<string | null>;
}

/** Контекст для модели: последние реплики, коротко, чтобы «да» после вопроса понималось. */
export function formatRelevanceInput(text: string, recent: { direction: "IN" | "OUT"; text: string }[]): string {
  const ctx = recent
    .slice(-4)
    .map((m) => `${m.direction === "IN" ? "Собеседник" : "Школа"}: ${m.text.slice(0, 200)}`)
    .join("\n");
  return (ctx ? `Предыдущие реплики:\n${ctx}\n\n` : "") + `ПОСЛЕДНЕЕ сообщение собеседника: ${text.slice(0, 600)}`;
}

/**
 * Полный разбор: сначала правила, потом модель. Модель недоступна или ответила
 * мусором — verdict.source = "fallback" и класс unclear (вызывающий решает, что
 * делать: на WhatsApp — повторить позже, где повторов нет — ответить как раньше).
 */
export async function classifyRelevance(
  text: string,
  recent: { direction: "IN" | "OUT"; text: string }[],
  deps: RelevanceDeps,
  hasMedia = false,
): Promise<RelevanceVerdict> {
  const byCode = codeRelevance(text, hasMedia);
  if (byCode) return byCode;
  // Вложение без подписи (голосовое, фото) модели правил не нужно: решает вызывающий.
  if (!text.trim()) return { cls: "unclear", source: "code", reason: "вложение без текста" };
  let raw: string | null = null;
  try {
    const hint = suspectedClass(text);
    raw = await deps.generate(
      RELEVANCE_PROMPT,
      formatRelevanceInput(text, recent) +
        (hint ? `\n\nПодсказка простых правил (может быть ошибкой, реши по смыслу и истории): ${hint}` : "")
    );
  } catch {
    raw = null;
  }
  const parsed = parseRelevance(raw);
  if (!parsed) return { cls: "unclear", source: "fallback", reason: "модель недоступна или ответила непонятно" };
  // Второй замок: модель назвала «по делу», а правила видят явный спам без слов о курсах — не верим.
  if (parsed.cls === "on_topic" && SPAM.test(text) && !STRONG_COURSE.test(text)) {
    return { cls: "unclear", source: "model", reason: `модель: по делу, но правила видят чужое (${parsed.reason})` };
  }
  return { cls: parsed.cls, source: "model", reason: parsed.reason };
}

export interface GateContext {
  /** Сколько раз уже задавали уточняющий вопрос этому человеку. */
  clarifiedBefore: number;
}

/** Что делаем с вердиктом. Чистая функция — вся политика видна в одном месте. */
export function decideAction(v: RelevanceVerdict, ctx: GateContext): RelevanceAction {
  if (ANSWERABLE.has(v.cls)) return "reply";
  if (v.cls === "unclear") {
    // Один нейтральный вопрос; не помогло — к человеку, дальше не гадаем.
    return ctx.clarifiedBefore < 1 ? "clarify" : "attention";
  }
  return "silent";
}

/** Нейтральный уточняющий вопрос. Таджикская фраза — дословно из шаблона самой Ширин. */
export function clarifyText(lang: "ru" | "tg" | "en"): string {
  if (lang === "tg") return "Ассалому алейкум! Ба шумо кадом маълумоти курсро равон кунем?";
  if (lang === "en") return "Hello! Which information about our courses would you like to get?";
  return "Здравствуйте! Какая информация о наших курсах вас интересует?";
}
