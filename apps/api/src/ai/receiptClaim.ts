import type { ClientLanguage } from "./clientLanguage.js";

/**
 * «Я ОТПРАВИЛА ЧЕК» — А ЧЕКА НЕТ.
 *
 * Живой прогон 05.09.2026 на сайте: на «Я оплатила, отправила чек, когда
 * придёт ссылка?» без единого вложения бот ответил «Кабул кардем, хозир дохил
 * мекнем» — подтвердил то, чего не получал. Модель видит слово «чек» в тексте
 * и верит ему; проверить, есть ли картинка на самом деле, может только код.
 *
 * Поэтому такое сообщение до модели не доходит вовсе: если человек говорит,
 * что прислал/прикрепил чек или что оплатил, а картинки в сообщении нет и в
 * этот ход ничего не спасено, отвечаем сами и одинаково — «чек пока не вижу,
 * прикрепите». Ложное «принято» здесь дороже любой неточности регэкспа:
 * человек уходит ждать ссылку, которая не придёт.
 */

/** Прошедшее время — «отправила», «скинул», «прикрепила»; настоящее первого
 *  лица — «отправляю», «прикрепляю». Инфинитив («как отправить чек?») сюда
 *  нарочно не входит: это вопрос, а не утверждение. */
const RU_SENT_VERB =
  "(?:(?:отправил|отослал|скинул|прислал|прикрепил|выслал|кинул|послал|загрузил|приложил)[аи]?|" +
  "отправляю|прикрепляю|скидываю|высылаю|кидаю|прилагаю)";
const RU_RECEIPT =
  "(?:чек\\p{L}*|скрин\\p{L}*|квитанц\\p{L}*|фото\\s+(?:чека|перевода|оплаты|платежа)|подтверждени\\p{L}*)";

const RU_CLAIMS = [
  // «отправила чек», «чек скинула», «вот чек».
  `(?<!\\p{L})${RU_SENT_VERB}(?!\\p{L})[^.!?\\n]{0,40}${RU_RECEIPT}`,
  `(?<!\\p{L})${RU_RECEIPT}[^.!?\\n]{0,40}(?<!\\p{L})${RU_SENT_VERB}(?!\\p{L})`,
  `(?<!\\p{L})(?:вот|держите)\\s+${RU_RECEIPT}`,
  // «я оплатила», «заплатил» — сам факт оплаты, без чека в руках.
  "(?<!\\p{L})(?:оплатил|заплатил|проплатил)[аи]?(?!\\p{L})",
  "(?<!\\p{L})(?:перев[её]л|перечислил)[аи]?\\s+(?:деньги|пул|сумму|оплату|\\d|на\\s+карту|на\\s+номер|вам)",
];

const TG_CLAIMS = [
  "пардохт\\s+кард(?:ам|ем)",
  "пул(?:ро|аша)?\\s+(?:андохтам|супоридам|гузарондам|партофтам|фиристодам|равон\\s+кардам)",
  "интиқол\\s+кардам|интикол\\s+кардам",
  "(?:чек|скрин|сурат|расм)\\p{L}*\\s+(?:фиристодам|партофтам|равон\\s+кардам|мондам|гузоштам|андохтам)",
  "(?:фиристодам|партофтам)\\s+(?:чек|скрин)",
  "(?:ана|инак|мана)\\s+чек",
];

const CLAIMS = new RegExp(`(?:${[...RU_CLAIMS, ...TG_CLAIMS].join("|")})`, "iu");

/** «Ещё не оплатила», «не получается отправить чек» — противоположный смысл.
 *  Таджикское отрицание — приставка («нафиристодам»): границы слова в CLAIMS
 *  её не пропускают, отдельного правила не нужно. */
const NEGATED = /(?<!\p{L})(?:не|нет|ещё\s+не|еще\s+не|пока\s+не|не\s+могу|не\s+получается)\s+\p{L}*(?:оплат|заплат|отправ|присл|скин|перев|прикреп|высл)/iu;

export function claimsReceiptSent(text: string): boolean {
  const trimmed = (text ?? "").trim();
  if (trimmed.length < 4) return false;
  if (NEGATED.test(trimmed)) return false;
  return CLAIMS.test(trimmed);
}

/**
 * Ответ без хода модели. На сайте у поля ввода есть скрепка; в Instagram и
 * Messenger её нет — там просим просто прислать фото сюда.
 */
export function receiptNotSeenReply(language: ClientLanguage, hasPaperclip: boolean): string {
  const texts: Record<ClientLanguage, { clip: string; plain: string }> = {
    ru: {
      clip: "Чек пока не вижу — прикрепите фото чека скрепкой, и я сразу проверю.",
      plain: "Чек пока не вижу — пришлите фото чека прямо сюда, и я сразу проверю.",
    },
    tg: {
      clip: "Чекро ҳоло намебинам — сурати чекро бо скрепка замима кунед, ҳамон замон тафтиш мекунам.",
      plain: "Чекро ҳоло намебинам — сурати чекро ҳамин ҷо фиристед, ҳамон замон тафтиш мекунам.",
    },
    en: {
      clip: "I don't see the receipt yet — attach a photo of it with the paperclip and I'll check right away.",
      plain: "I don't see the receipt yet — send a photo of it right here and I'll check right away.",
    },
  };
  return hasPaperclip ? texts[language].clip : texts[language].plain;
}
