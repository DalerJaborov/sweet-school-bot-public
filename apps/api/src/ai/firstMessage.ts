/** Признаки настоящего вопроса — даже если слова вокруг «курсовые». */
const QUESTION_SIGNAL =
  /\?|(?<!\p{L})(чанд|чи|чӣ|чиба|чаро|кай|куҷо|кучо|кадом|оё|чихел|чӣ\s*хел|нарх\p{L}*|сколько|когда|где|как|какие|какой|какая|почему|цена|стоит|стоимость|сертификат|рецепт\p{L}*|онлайн|офлайн|оффлайн|адрес|телеграм|ватсап|whatsapp|telegram|сайт|скидк\p{L}*|оплат\p{L}*|пардохт|номер|карт\p{L}*)(?!\p{L})/iu;

/**
 * true — первое сообщение подходит под меню воронки (приветствие, «курс»,
 * «маълумот»); false — это вопрос или вложение, меню не шлём, отвечает ИИ.
 */
export function funnelMenuFits(text: string | null | undefined, hasAttachments = false): boolean {
  if (hasAttachments) return false;
  const raw = (text ?? "").trim();
  if (!raw) return true;
  if (isTrivialMessage(raw)) return true;
  if (QUESTION_SIGNAL.test(raw)) return false;
  const words = raw
    .toLowerCase()
    .replace(/ё/g, "е")
    .split(/[^\p{L}\p{N}+]+/u)
    .filter(Boolean);
  if (words.length === 0) return true;
  if (words.length > 6) return false; // длинное сообщение — это уже разговор, а не «салом»
  return words.every((w) => MENU_WORDS.has(w) || isTrivialMessage(w));
}
