import crypto from "node:crypto";
import { env } from "../env.js";

/**
 * ОТДЕЛЬНЫЙ СЕКРЕТ ДЛЯ ТОКЕНОВ УЧЕНИЦ.
 *
 * Найдено разбором безопасности 03.09.2026, и это была дыра во всю стену.
 * Ссылка на курс подписывалась ТЕМ ЖЕ секретом, что и вход владельца в панель,
 * а проверка админского доступа сводилась к «подпись верна» — про содержимое
 * токена никто не спрашивал. То есть любая ученица, купившая курс за сто
 * сомони, могла взять токен прямо из адресной строки и открыть им всю панель:
 * базу клиенток, переписки, чеки, ключи. И перезаписать настройки.
 *
 * Починка двойная, и обе половины нужны.
 *
 * Первая — проверка роли в admin.ts: токен ученицы роли «admin» не несёт и
 * дверь не откроет. Одного этого достаточно, чтобы дыру закрыть.
 *
 * Вторая — этот файл: токены учениц подписываются ДРУГИМ секретом, так что
 * классы токенов не пересекаются физически. Забыть проверку роли в новом
 * обработчике — обычное дело; тогда сработает второй рубеж.
 *
 * Секрет выводится из основного, а не заводится отдельной переменной
 * окружения. Причина простая: новая обязательная переменная означает, что при
 * ближайшем разворачивании на чистом сервере приложение не поднимется вовсе, а
 * человек, который будет это разворачивать, не программист. Вывод по HMAC даёт
 * ту же несовместимость ключей без единой правки в окружении.
 */

/** Метка назначения. Менять её нельзя: сменишь — умрут все живые ссылки. */
const PURPOSE = "sweet-school-course-tokens-v1";

let cached: string | null = null;

export function courseTokenSecret(): string {
  if (!cached) {
    cached = crypto.createHmac("sha256", env.jwtSecret).update(PURPOSE).digest("hex");
  }
  return cached;
}

/**
 * Секреты для ПРОВЕРКИ, по порядку: сначала нынешний, потом прежний общий.
 *
 * Прежний нужен на переход. В день выкладки у учениц на руках уже есть живые
 * ссылки и открытые сессии, подписанные старым секретом; выкинуть их значит
 * выгнать всех разом посреди урока. Старый секрет принимается только на
 * проверку и только для токенов ученицы — панель его больше не признаёт вовсе,
 * а значит дыра закрыта с первой минуты.
 *
 * Убрать вторую строчку можно НЕ РАНЬШЕ 04.09.2027: ссылки живут 7 дней, но
 * сессии — 365 (SESSION_TTL_DAYS в access.ts). Снять раньше значит выгнать
 * всех, кто вошёл до 03.09.2026, разом.
 */
export function courseVerifySecrets(): string[] {
  return [courseTokenSecret(), env.jwtSecret];
}

/** Только для тестов: сбросить вычисленный секрет. */
export function resetCourseTokenSecret(): void {
  cached = null;
}
