import { getSetting } from "../db.js";

/**
 * РУБИЛЬНИК «УСКОРЕНИЕ ПЛАТФОРМЫ» (`courseSpeedMode`, панель → Настройки).
 *
 * Сервер только сообщает странице ученицы, включено ли оно (поле `speed` в
 * /me); всё остальное решает клиент (src/course/speed.ts). Включённое
 * ускорение НЕ трогает защиту: шифрование HLS, подписанные ссылки, привязка
 * устройства и срок офлайн-ключа проверяются ровно так же. По умолчанию —
 * выключено: новая возможность не включается сюрпризом после выкладки.
 */
export async function speedModeOn(): Promise<boolean> {
  return (await getSetting("courseSpeedMode"))?.trim() === "on";
}
