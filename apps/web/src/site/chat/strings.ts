import type { Lang } from "../i18n";

/**
 * Строки чата, которых нет (и не должно быть) в общем словаре сайта
 * (src/site/i18n.ts — им владеет другой агент). Приветствие и быстрые
 * реплики — «живая» часть виджета, специфичная только для чата, поэтому
 * живут рядом с ним и попадают в тот же ленивый чанк.
 */
export type ChatStrings = {
  /** Приветствие при первом открытии (без истории) — НЕ ответ ИИ. */
  greeting: string;
  /** Подсказки-чипы под приветствием — отправляются как обычное сообщение. */
  quickReplies: string[];
  /** Плейсхолдер поля ввода, когда человек явно собирается прислать чек. */
  uploadPlaceholder: string;
  /** Подпись у галочки «доставлено» под своим сообщением. */
  sent: string;
  /** Подпись у спиннера загрузки картинки. */
  uploading: string;
};

const ru: ChatStrings = {
  greeting: "Здравствуйте! Я на связи — спросите про курсы, цену или пришлите чек об оплате.",
  quickReplies: ["Сколько стоит?", "Как оплатить?", "Курс в Душанбе", "Хочу купить"],
  uploadPlaceholder: "Пришлите чек — ссылка придёт сюда",
  sent: "Доставлено",
  uploading: "Загрузка…",
};

const tg: ChatStrings = {
  greeting: "Ассалому алейкум! Пурсед дар бораи курсҳо, нарх ё чеки пардохтро фиристед.",
  quickReplies: ["Нархаш чанд?", "Чӣ тавр пардохт кунам?", "Курс дар Душанбе", "Мехоҳам харам"],
  uploadPlaceholder: "Чекро фиристед — истинод ин ҷо меояд",
  sent: "Фиристода шуд",
  uploading: "Бор карда истодааст…",
};

const CHAT_STRINGS: Record<Lang, ChatStrings> = { ru, tg };

export function chatStrings(lang: Lang): ChatStrings {
  return CHAT_STRINGS[lang];
}
