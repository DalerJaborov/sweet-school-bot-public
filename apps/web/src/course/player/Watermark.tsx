/**
 * Именной знак поверх видео — неподвижный, мелкий, в правом верхнем углу
 * (решение владельца 08.11.2026: прыгающее по экрану имя мешало смотреть).
 * Лежит внутри обёртки плеера, поэтому остаётся и в полноэкранном режиме.
 */
export function Watermark({ text }: { text: string }) {
  return (
    <div className="player-mark" aria-hidden="true">
      {text}
    </div>
  );
}
