/**
 * ПЕРЕЗАГРУЗКА БЕЗ ТОКЕНА после входа по ссылке (дизайн доступа 03.09.2026).
 *
 * Почему не history.replaceState, как раньше: личный манифест
 * (/api/course/app.webmanifest) браузер запрашивает один раз при загрузке
 * страницы, а в тот момент куки сессии ещё не было — в нём лежал безличный
 * start_url. Перезагрузка уже с кукой даёт манифест с `?pair=`, и
 * установленное с экрана «Домой» приложение сможет войти само. Токен при
 * этом в историю не попадает: replace, а не assign.
 *
 * ВСЕГДА на /course, а не на текущий window.location.pathname: для короткой
 * ссылки /l/<код> (04.09.2026) код живёт в самом пути, а не в ?token=, и
 * «оставить путь как есть» просто перезагружало ту же /l/<код> — bootstrap()
 * находил код снова, открывал сессию снова и снова звал reloadWithoutToken —
 * бесконечная перезагрузка, ни разу не долетавшая до уроков (найдено
 * ревизией 05.09.2026 на реальной короткой ссылке). Для старых ссылок вида
 * /course?token=… результат тот же самый: там pathname и так был /course.
 *
 * Отдельный модуль — чтобы тесты подменяли его целиком: jsdom переход по
 * адресу не умеет и молча ничего не делает.
 */
export function reloadWithoutToken(): void {
  window.location.replace("/course");
}
