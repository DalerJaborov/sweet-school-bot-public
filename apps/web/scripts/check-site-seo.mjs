/** Offline checks of the HTML actually generated for people and crawlers.
 * No fetches, scripts, external resources or arbitrary SEO length scores.
 */
import path from "node:path";
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { JSDOM } from "jsdom";
import { loadContent, renderSite, WEB_ROOT } from "./build-site-pages.mjs";

const DEFAULT_APP_PATHS = ["/course", "/l", "/panel", "/api", "/admin"];
const normalizedText = (value) => (value ?? "").trim().replace(/\s+/g, " ").toLocaleLowerCase();

function routeForFile(file) {
  if (file === "site.html" || file === "index.html") return "/";
  return `/${file.replace(/index\.html$/, "").replace(/\.html$/, "")}`;
}

/** Returns actionable errors; callers can test mutated HTML without disk/network IO. */
export function auditSite(files, { origin, appPaths = DEFAULT_APP_PATHS } = {}) {
  const base = new URL(origin).origin;
  const errors = [];
  const fail = (code, file, message) => errors.push({ code, file, message });
  const records = [];
  const byUrl = new Map();
  const titles = new Map();
  const descriptions = new Map();
  const doms = [];
  try {
    for (const [file, html] of files) {
      if (!file.endsWith(".html")) continue;
      const url = new URL(routeForFile(file), base).href;
      // jsdom does not load subresources or execute scripts with these defaults.
      const dom = new JSDOM(html, { url });
      doms.push(dom);
      const doc = dom.window.document;
      const noindex = [...doc.querySelectorAll('meta[name="robots" i], meta[name="googlebot" i]')]
        .some((el) => /(?:^|[\s,])(noindex|none)(?:[\s,]|$)/i.test(el.content));
      const record = { file, url, doc, noindex, lang: doc.documentElement.lang, alts: new Map() };
      records.push(record);
      if (byUrl.has(url)) fail("duplicate-route", file, `Route also generated by ${byUrl.get(url).file}: ${url}`);
      byUrl.set(url, record);

      for (const [selector, label, seen] of [
        ["head title", "title", titles],
        ['head meta[name="description" i]', "description", descriptions],
      ]) {
        const nodes = doc.querySelectorAll(selector);
        const value = normalizedText(label === "title" ? nodes[0]?.textContent : nodes[0]?.getAttribute("content"));
        if (nodes.length !== 1 || !value) fail(`invalid-${label}`, file, `Expected one nonempty ${label}`);
        if (!noindex && value) {
          if (seen.has(value)) fail(`duplicate-${label}`, file, `Same ${label} as ${seen.get(value)}`);
          else seen.set(value, file);
        }
      }
      const h1 = doc.querySelectorAll("h1");
      if (h1.length !== 1 || !normalizedText(h1[0]?.textContent)) fail("invalid-h1", file, "Expected one nonempty h1");
      const canonicals = doc.querySelectorAll('link[rel~="canonical"]');
      if (canonicals.length !== 1 || canonicals[0]?.getAttribute("href") !== url) {
        fail("invalid-canonical", file, `Expected exactly one self canonical: ${url}`);
      }
      if (!record.lang) fail("missing-language", file, "HTML lang is missing");
      const scripts = doc.querySelectorAll('script[type="application/ld+json"]');
      if (!noindex && !scripts.length) fail("missing-jsonld", file, "No JSON-LD found");
      for (const script of scripts) {
        try {
          const data = JSON.parse(script.textContent);
          if (!data || typeof data !== "object") throw new Error("Expected an object or array");
        } catch (error) {
          fail("invalid-jsonld", file, error.message);
        }
      }
      const catalog = doc.getElementById("courses-island");
      if (catalog) {
        // Vite must preserve these server-side directives, including fallback.
        const walker = doc.createTreeWalker(catalog, dom.window.NodeFilter.SHOW_COMMENT);
        const comments = [];
        while (walker.nextNode()) comments.push(walker.currentNode.data.trim());
        const includes = comments.filter((comment) => /^#\s*include\b/.test(comment));
        const expectedQuery = `lang=${record.lang}${catalog.dataset.course ? `&only=${encodeURIComponent(catalog.dataset.course)}` : ""}`;
        const expectedVirtual = `/_site/catalog-fragment?${expectedQuery}`;
        const block = comments.findIndex((comment) => /^#\s*block\s+name="catalog-fallback"\s*$/.test(comment));
        const end = comments.findIndex((comment) => /^#\s*endblock\s*$/.test(comment));
        const include = comments.findIndex((comment) => /^#\s*include\b/.test(comment));
        if (includes.length !== 1 || !includes[0].includes(`virtual="${expectedVirtual}"`) ||
            !includes[0].includes('stub="catalog-fallback"') || block < 0 || end <= block || include <= end) {
          fail("invalid-catalog-ssi", file, `Expected preserved SSI block/fallback and include for ${expectedVirtual}`);
        }
      }
      for (const alternate of doc.querySelectorAll('link[rel~="alternate"][hreflang]')) {
        const lang = alternate.getAttribute("hreflang");
        if (record.alts.has(lang)) fail("duplicate-hreflang", file, `Repeated language: ${lang}`);
        record.alts.set(lang, alternate.getAttribute("href"));
      }
    }
    if (!records.length) fail("no-pages", "site", "No rendered HTML pages found");
    const indexable = records.filter((record) => !record.noindex);
    const languages = new Set(indexable.map((record) => record.lang).filter(Boolean));
    for (const record of records) {
      const { doc, file, url, alts, noindex, lang } = record;
      if (!noindex) {
        for (const expected of [...languages, "x-default"]) {
          if (!alts.has(expected)) fail("missing-hreflang", file, `Missing alternate: ${expected}`);
        }
        if (alts.get(lang) !== url) fail("invalid-hreflang-self", file, `Alternate ${lang} must point to this page`);
      }
      for (const [alternateLang, href] of alts) {
        if (!languages.has(alternateLang) && alternateLang !== "x-default") {
          fail("invalid-hreflang", file, `Unsupported site language: ${alternateLang}`);
        }
        const target = byUrl.get(href);
        if (!target || target.noindex) {
          fail("invalid-hreflang-target", file, `Alternate must be an indexable canonical URL: ${href}`);
          continue;
        }
        if (alternateLang !== "x-default" && target.lang !== alternateLang) {
          fail("invalid-hreflang-language", file, `${href} has lang=${target.lang}, not ${alternateLang}`);
        }
        for (const [clusterLang, clusterHref] of alts) {
          if (target.alts.get(clusterLang) !== clusterHref) {
            fail("nonreciprocal-hreflang", file, `${href} disagrees on alternate ${clusterLang}`);
          }
        }
      }
      for (const anchor of doc.querySelectorAll("a[href], area[href]")) {
        const href = anchor.getAttribute("href").trim();
        let targetUrl;
        try {
          if (!href) throw new Error("Empty href");
          targetUrl = new URL(href, url);
          if (!["http:", "https:", "mailto:", "tel:"].includes(targetUrl.protocol)) throw new Error("Unsupported link protocol");
          if (["mailto:", "tel:"].includes(targetUrl.protocol) && !targetUrl.pathname) throw new Error("Empty contact link");
        } catch (error) {
          fail("invalid-link", file, `${href}: ${error.message}`);
          continue;
        }
        if (targetUrl.origin !== base) continue; // External links: syntax only, never fetched.
        const target = byUrl.get(`${base}${targetUrl.pathname}`);
        if (!target) {
          const isApp = appPaths.some((app) => targetUrl.pathname === app || targetUrl.pathname.startsWith(`${app}/`));
          if (!isApp) fail("broken-link", file, `No generated public route or allowed app: ${href}`);
          continue;
        }
        if (targetUrl.hash) {
          let id;
          try { id = decodeURIComponent(targetUrl.hash.slice(1)); }
          catch { fail("invalid-anchor", file, `Invalid fragment encoding: ${href}`); continue; }
          if (!target.doc.getElementById(id) && ![...target.doc.querySelectorAll("a[name]")].some((a) => a.name === id)) {
            fail("broken-anchor", file, `Missing anchor in ${target.file}: ${href}`);
          }
        }
      }
    }

    const sitemapFile = "public/sitemap.xml";
    const sitemap = files.get(sitemapFile);
    if (!sitemap) fail("missing-sitemap", sitemapFile, "Sitemap is missing");
    else {
      try {
        const xml = new JSDOM(sitemap, { contentType: "text/xml" });
        doms.push(xml);
        const xmlDoc = xml.window.document;
        const namespace = "http://www.sitemaps.org/schemas/sitemap/0.9";
        if (xmlDoc.documentElement.localName !== "urlset" || xmlDoc.documentElement.namespaceURI !== namespace) {
          fail("invalid-sitemap", sitemapFile, "Expected a sitemap urlset with the sitemap namespace");
        }
        const expected = new Set(indexable.map((record) => record.url));
        const listed = new Set();
        for (const entry of xmlDoc.getElementsByTagNameNS(namespace, "url")) {
          const locs = entry.getElementsByTagNameNS(namespace, "loc");
          const loc = locs[0]?.textContent.trim();
          if (locs.length !== 1 || !loc) fail("invalid-sitemap-loc", sitemapFile, "Each url needs one nonempty loc");
          if (listed.has(loc)) fail("duplicate-sitemap-url", sitemapFile, `Repeated URL: ${loc}`);
          listed.add(loc);
          if (!expected.has(loc)) fail("unexpected-sitemap-url", sitemapFile, `Not an indexable canonical URL: ${loc}`);
          for (const alternate of entry.getElementsByTagNameNS("http://www.w3.org/1999/xhtml", "link")) {
            if (byUrl.get(loc)?.alts.get(alternate.getAttribute("hreflang")) !== alternate.getAttribute("href")) {
              fail("invalid-sitemap-hreflang", sitemapFile, `Alternate disagrees with HTML: ${loc}`);
            }
          }
        }
        for (const url of expected) if (!listed.has(url)) fail("missing-sitemap-url", sitemapFile, `Missing URL: ${url}`);
      } catch (error) {
        fail("invalid-sitemap", sitemapFile, error.message);
      }
    }
    return { errors, pageCount: records.length, indexableCount: indexable.length };
  } finally {
    for (const dom of doms) dom.window.close();
  }
}

/** Check actual build artifacts, including private shells excluded from public SEO. */
export function auditBuiltSite(distDir, content = loadContent()) {
  const files = new Map();
  const artifactErrors = [];
  const expected = renderSite(content);
  const fail = (code, file, message) => artifactErrors.push({ code, file, message });
  for (const directory of ["", "tg"]) {
    const fullDir = path.join(distDir, directory);
    if (!fs.existsSync(fullDir)) continue;
    for (const entry of fs.readdirSync(fullDir, { withFileTypes: true })) {
      if (!entry.isFile() || !entry.name.endsWith(".html")) continue;
      const file = directory ? `${directory}/${entry.name}` : entry.name;
      const html = fs.readFileSync(path.join(fullDir, entry.name), "utf8");
      if (file === "index.html" || file === "course.html") {
        const dom = new JSDOM(html);
        try {
          const robots = [...dom.window.document.querySelectorAll('meta[name="robots" i]')];
          if (!robots.some((meta) => /(?:^|[\s,])(noindex|none)(?:[\s,]|$)/i.test(meta.content))) {
            fail("private-app-indexable", file, "Private application shell must retain noindex after build");
          }
        } finally { dom.window.close(); }
      } else files.set(file, html);
    }
  }
  for (const name of ["sitemap.xml", "robots.txt"]) {
    const fullPath = path.join(distDir, name);
    if (fs.existsSync(fullPath)) files.set(`public/${name}`, fs.readFileSync(fullPath, "utf8"));
  }
  for (const file of expected.keys()) {
    if (!files.has(file)) fail("missing-build-artifact", file, "Expected generated artifact is absent from dist");
    else if (expected.get(file).includes('id="courses-island"')) {
      const dom = new JSDOM(files.get(file));
      try {
        if (!dom.window.document.getElementById("courses-island")) fail("missing-catalog", file, "Build removed the public catalogue container");
      } finally { dom.window.close(); }
    }
  }
  for (const file of ["index.html", "course.html"]) {
    if (!fs.existsSync(path.join(distDir, file))) fail("missing-build-artifact", file, "Expected application shell is absent from dist");
  }
  const result = auditSite(files, { origin: content.site.origin });
  return { ...result, errors: [...artifactErrors, ...result.errors] };
}

function main() {
  const content = loadContent();
  const built = process.argv.includes("--dist");
  const result = built ? auditBuiltSite(path.join(WEB_ROOT, "dist"), content) : auditSite(renderSite(content), { origin: content.site.origin });
  if (result.errors.length) {
    for (const error of result.errors) console.error(`[${error.code}] ${error.file}: ${error.message}`);
    process.exitCode = 1;
  } else {
    console.log(`SEO checks passed (${built ? "dist" : "generated"}): ${result.pageCount} HTML pages, ${result.indexableCount} indexable URLs; no network requests.`);
  }
}

